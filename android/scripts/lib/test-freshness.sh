#!/usr/bin/env bash
# Свежесть результатов тестов.
#
# ЗАЧЕМ. Gradle помечает :common:desktopTest как UP-TO-DATE, когда считает входы
# неизменными. Тесты при этом не выполняются, а XML с прошлого раза остаются на
# месте — сводка показывает прошлые числа, и «всё зелено» превращается в отчёт о
# прогоне, которого не было. Такой зелёный отчёт уже один раз ввёл проверяющего
# в заблуждение, поэтому свежесть проверяется отдельно от кода выхода Gradle.
#
# Функция вынесена в lib, чтобы её саму можно было прогнать в scripts/tests/run.sh:
# сторож, которого никто не проверял, — не сторож.

# fresh_results <файл-метка> <каталог с результатами>
# 0 — найден хотя бы один TEST-*.xml и все они новее метки;
# 1 — результатов нет вовсе либо хотя бы один остался от прошлого прогона.
fresh_results() {
    local mark="$1" dir="$2" f found=0
    while IFS= read -r f; do
        found=1
        [ "$f" -nt "$mark" ] || return 1
    done < <(find "$dir" -name 'TEST-*.xml' 2>/dev/null)
    [ "$found" -eq 1 ]
}
