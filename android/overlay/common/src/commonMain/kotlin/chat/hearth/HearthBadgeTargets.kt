package chat.hearth

/**
 * Кому и что уходит, когда число непрочитанных рисуется на иконке.
 *
 * Значок на Huawei/Honor ставится вызовом провайдера лаунчера, а на старых EMUI, где
 * провайдера нет, — рассылкой `CHANGE_BADGE`. Рассылка несёт наружу имя нашего пакета и
 * число непрочитанных: пока она уходила неявной, её получал любой работающий рядом
 * receiver с подходящим фильтром — то есть постороннее приложение узнавало, что Очагом
 * пользуются и сколько в нём непрочитанного.
 *
 * Поэтому адресат всегда явный, а список адресатов лежит здесь, в общем коде: androidMain
 * с Context тестами не покрывается, а вот «рассылка без явного адресата» — это инвариант,
 * который можно закрепить проверяемо (HearthBadgeTest).
 */
object HearthBadgeTargets {

  const val CHANGE_BADGE = "com.huawei.android.launcher.action.CHANGE_BADGE"

  /**
   * Лаунчеры, понимающие эту рассылку: EMUI и его наследник на Honor. Именно пакеты, а не
   * компоненты: имя receiver'а у EMUI плавает от версии к версии, и явный ComponentName
   * молча сломал бы значок, а setPackage даёт ту же адресность без хрупкости.
   */
  val LAUNCHERS = listOf("com.huawei.android.launcher", "com.hihonor.android.launcher")

  /** Лаунчер рисует две цифры: больше 99 слать незачем, отрицательное — тем более. */
  fun badgeNumber(count: Int): Int = count.coerceIn(0, 99)

  /**
   * Кому рассылка уходит на самом деле.
   *
   * Список выше правят руками, а `setPackage("")` — это не «всем», но и не адрес: рассылка
   * просто уходит в никуда, и молча переставший обновляться значок никто не свяжет с
   * опечаткой. Поэтому между списком и `sendBroadcast` стоит фильтр, а не доверие к списку:
   * проверка, которую вызывают, и проверка, которая просто написана, — разные вещи.
   *
   * Пустой результат означает «рассылать некому»: HearthBadge тогда не шлёт ничего, и это
   * верно — значок покажет уведомление, связь и звонки от этого не зависят.
   */
  fun broadcastTargets(): List<String> = LAUNCHERS.filter(::isAddressable)

  /**
   * Годится ли строка как явный адресат рассылки. Пустая строка здесь опаснее всего:
   * `setPackage("")` — это не «всем», но и не адрес, а ошибка, которую легко не заметить
   * глазами в списке выше.
   */
  fun isAddressable(pkg: String): Boolean =
    pkg.length in 3..255 &&
      !pkg.startsWith('.') && !pkg.endsWith('.') && !pkg.contains("..") && pkg.contains('.') &&
      pkg.all { it in 'a'..'z' || it in '0'..'9' || it == '.' || it == '_' }
}
