package chat.hearth

import chat.simplex.common.model.ChatController
import chat.simplex.common.platform.Log

/**
 * Пин ICE на свой узел в точке, где список РЕАЛЬНО берут — перед звонком.
 *
 * # Почему проверки на входе оказалось мало
 *
 * Пин уже был, но только на путях, которыми данные ПРИХОДЯТ: [HearthBundle.validate]
 * проверяет отсканированный QR, [HearthTurnCredentials.parse] — ответ узла. Обе
 * записывают результат в одну и ту же настройку `webrtcIceServers`. А читал её
 * `getIceServers()` в `views/call/WebRTC.kt` — и читал как есть, без единой проверки.
 * Теперь там стоит [hearthPinnedIceServers] — одна строка в дереве форка, и вся она.
 *
 * Значит любая запись мимо этих двух путей полностью управляет маршрутом медиа:
 * экран ручной правки ICE в настройках звонков, восстановление старой базы, `adb` на
 * отладочной сборке. Проверка источника — не то же самое, что инвариант потребителя,
 * и держать надо именно инвариант: «звонок уходит только через узел этой семьи».
 *
 * # Почему чужая запись теперь ОТБРАСЫВАЕТСЯ, а не травит весь список
 *
 * Сначала было наоборот: одна чужая строка обнуляла список целиком. Довод звучал так:
 * маршрут из списка выбирает сам WebRTC, значит оставить «только хорошие» записи —
 * значит оставить выбор ему. Довод верен ровно наполовину. Выбор WebRTC ограничен тем,
 * что ему дали: если в списке остались ТОЛЬКО наши записи, уйти мимо узла ему некуда.
 *
 * А цена прежнего решения оказалась чужой: `ALWAYS_RELAY = true` (HearthPresets.kt)
 * ставит `iceTransportPolicy: "relay"`, `defaultIceServers` в форке пуст, и пустой
 * список ICE означает не «звонок пойдёт напрямую», а «звонка не будет вовсе». Под это
 * попадали телефоны, заведённые старой сборкой, переезд узла на другое имя и
 * восстановление базы — то есть обычная жизнь семьи, а не атака. Причём молча.
 *
 * Поэтому правило другое: чужое выбрасываем, своё оставляем, и НИ ОДИН путь не
 * заканчивается пустым списком, пока у устройства есть хоть какой-то ICE.
 *
 * # Порядок запасных источников
 *
 *   1. настройка `webrtcIceServers`, очищенная от чужих записей — обычный случай;
 *   2. список ICE из применённого bundle ([HearthPrefs.bundleIce]) — он пришёл с узла
 *      вместе с адресами релеев, то есть из того же QR или кода доступа, который
 *      человек получил лично;
 *   3. то, что лежит в настройке (а если её нет — то, что лежит в bundle), КАК ЕСТЬ —
 *      старое поведение upstream, плюс предупреждение человеку.
 *
 * Третий шаг — осознанный fail-open. Он включается только тогда, когда иначе звонков
 * не будет совсем, и он не бесшумный: строка уходит на экран «Узел» и один раз за
 * сеанс показывается окном. Тихий отказ здесь хуже: «звонки перестали работать» без
 * объяснения семья чинит переустановкой приложения, а не звонком владельцу узла.
 *
 * # Почему непроверенный список СНИМАЕТ relay-only
 *
 * Третий шаг чуть не обернулся защитой наизнанку. Список непустой, значит
 * [hearthUseRelay] по старому правилу оставлял `iceTransportPolicy: "relay"` — и медиа
 * ПРИНУДИТЕЛЬНО шло через ретранслятор, про который мы только что признали, что не
 * знаем, чей он. До правки чужой сервер был лишь ОДНИМ из возможных маршрутов, и
 * WebRTC чаще всего выбирал прямой; после — становился ЕДИНСТВЕННЫМ. То есть строгость
 * не охраняла ничего, а ровно тот вред, которого боялись, делала обязательным.
 *
 * Поэтому у выбора есть второе поле — [HearthIceChoice.verified]. Пока оно `true`,
 * relay-only держится: ретранслятор наш, и прятать за ним адреса устройств правильно.
 * Как только оно `false` — relay-only снимается, и остаётся выбор человека
 * (`webrtcPolicyRelay`), то есть поведение upstream: звонок идёт как получится, чаще
 * всего напрямую. Шифрование медиа (DTLS-SRTP) от этого никуда не девается, теряется
 * только сокрытие адреса — и человеку про это сказано словами.
 *
 * Правило целиком: **ни один путь не принуждает медиа идти через сервер, про который
 * не доказано, что он наш.**
 */

/**
 * Отфильтровать список ICE перед звонком.
 *
 * @param entries строки ICE в том же виде, в каком они лежат в настройках.
 * @param expectedHost хост своего узла или `null`, если он этому устройству неизвестен.
 * @return записи, про которые ДОКАЗАНО, что они указывают на свой узел, приведённые к
 *   каноническому виду (см. [hearthNormalizeIceEntry]). Пустой список — доказать не
 *   удалось ни про одну.
 *
 * # Почему неизвестный хост даёт ПУСТОЙ ответ, а не весь список
 *
 * Раньше при `expectedHost == null` список возвращался целиком и без единой проверки,
 * то есть проходил дальше как проверенный. А «проверенный» ниже по течению означает
 * relay-only: медиа принудительно шло через сервер, чью принадлежность никто не
 * подтверждал. Звонки это не спасало, а вред делало обязательным.
 *
 * Связи это не отнимает: тот же список отдаёт [hearthIceChoice] третьей ступенью, но
 * уже честно помеченным как непроверенный — без relay-only и с предупреждением. Здесь
 * же ответ означает ровно то, что написано в имени: сколько записей ПРИПИСАНО к своему
 * узлу. Не с чем сверять — приписать нечего.
 *
 * Чистая функция: ни настроек, ни платформы — чтобы её можно было прогнать на JVM.
 */
fun hearthPinnedIce(entries: List<String>, expectedHost: String?): List<String> {
  val clean = entries.map { it.trim() }.filter { it.isNotEmpty() }
  if (clean.isEmpty() || expectedHost == null) return emptyList()
  return clean
    .filter { runCatching { requireIceEntry(it, expectedHost) }.isSuccess }
    .map { hearthNormalizeIceEntry(it) }
}

/**
 * Что отдать звонку и что при этом сказать человеку.
 *
 * @param servers список ICE для WebRTC. Пустым бывает ровно в одном случае: у
 *   устройства нет ни одной записи ICE ни в настройках, ни в bundle.
 * @param notice строка человеку или `null`. Непустая означает «звонок, скорее всего,
 *   пройдёт, но защита слабее обещанной» — молчать об этом нельзя.
 * @param verified доказано ли, что КАЖДАЯ запись в [servers] указывает на свой узел.
 *   Это и есть право включать relay-only: `true` — медиа обязано идти через наш
 *   ретранслятор; `false` — принуждать нельзя, потому что принуждали бы к чужому
 *   серверу (см. [hearthUseRelay]). Умолчания у поля нет намеренно: «проверено»
 *   должно быть написано, а не получиться само.
 */
data class HearthIceChoice(
  val servers: List<String>,
  val notice: String? = null,
  val verified: Boolean,
)

/**
 * Выбор списка ICE. Чистая функция — вся развилка проверяется на JVM.
 *
 * @param configured то, что лежит в `webrtcIceServers`.
 * @param bundleIce ICE из применённого bundle ([HearthPrefs.bundleIce]).
 * @param expectedHost хост своего узла; `null` — неизвестен, сверять не с чем.
 */
fun hearthIceChoice(
  configured: List<String>,
  bundleIce: List<String>,
  expectedHost: String?,
): HearthIceChoice {
  val clean = configured.map { it.trim() }.filter { it.isNotEmpty() }
  val bundleClean = bundleIce.map { it.trim() }.filter { it.isNotEmpty() }
  val kept = hearthPinnedIce(clean, expectedHost)
  if (kept.isNotEmpty()) {
    // Часть записей отброшена — это не поломка, но и не пустяк: кто-то или что-то
    // дописало в список чужой сервер. Звонки при этом работают.
    val notice = if (kept.size < clean.size) HearthIceText.FOREIGN_DROPPED else null
    return HearthIceChoice(kept, notice, verified = true)
  }

  // Своих записей в настройке не осталось. Берём то, что пришло с узла вместе с
  // адресами релеев: bundle человек получил лично, и подменить его по сети нельзя.
  val fromBundle = hearthPinnedIce(bundleClean, expectedHost)
  if (fromBundle.isNotEmpty()) {
    return HearthIceChoice(fromBundle, HearthIceText.FELL_BACK_TO_BUNDLE, verified = true)
  }

  // Подтвердить не удалось ничего. Случая два, и различаются они только текстом:
  // либо хост своего узла известен, а записи ему не принадлежат, либо хоста нет вовсе
  // и сверять не с чем. Последствия у обоих одинаковые и объявляются здесь: список
  // отдаётся КАК ЕСТЬ (иначе звонков не будет совсем), помечается непроверенным —
  // значит relay-only не включится и медиа не погонят через неизвестный сервер, — и
  // человек получает строку про то, что при этом меняется.
  val unverified = clean.ifEmpty { bundleClean }
  if (unverified.isNotEmpty()) {
    val notice = if (expectedHost == null) HearthIceText.UNKNOWN_HOST else HearthIceText.UNVERIFIED
    return HearthIceChoice(unverified, notice, verified = false)
  }

  // ICE нет вовсе: устройство не заведено или настройки стёрты. Звонок в этом случае
  // идёт по-старому (без обязательного ретранслятора), а человека посылаем на «Узел».
  return HearthIceChoice(emptyList(), HearthIceText.NO_SERVERS, verified = false)
}

/**
 * Пускать ли медиа только через ретранслятор.
 *
 * # Почему это не просто [HearthPresets.ALWAYS_RELAY]
 *
 * `iceTransportPolicy: "relay"` означает «ходить только через сервер из списка ICE».
 * При ПУСТОМ списке это не «строже», а «никак»: ретранслятора нет, прямой путь
 * запрещён, звонок не состоится. То есть ровно в этом случае строгость не охраняет
 * ничего и только отнимает связь — это и есть тот размен, из-за которого одна осечка
 * в списке ICE оборачивалась полным отсутствием звонков у семьи.
 *
 * Поэтому relay-only держится, пока есть чем ретранслировать. Списка нет — остаётся
 * выбор человека (`webrtcPolicyRelay`), то есть поведение upstream: звонок попробует
 * пройти напрямую, а о том, что при этом видно собеседнику, человеку уже сказано
 * ([HearthIceText.NO_SERVERS]).
 *
 * # Почему мало «список непустой»
 *
 * Список бывает непустым и НЕПРОВЕРЕННЫМ: третья ступень [hearthIceChoice] отдаёт то,
 * что лежит в настройках, когда своих записей не нашлось нигде. На таком списке
 * relay-only означал бы «идти только через сервер, про который мы сами написали
 * человеку, что не знаем, чей он» — то есть делал бы утечку адресов и медиапотока
 * обязательной там, где без него она была бы лишь возможной. Строгость, которая
 * увеличивает вред, — не строгость.
 *
 * Поэтому непроверенный список снимает relay-only так же, как его снимает пустой:
 * остаётся выбор человека. Прямое соединение при этом остаётся зашифрованным
 * (DTLS-SRTP), теряется только сокрытие адреса устройства — ровно то, о чём говорит
 * [HearthIceText.UNVERIFIED] и [HearthIceText.UNKNOWN_HOST].
 *
 * @param iceServers то, что вернул `getIceServers()`.
 * @param preferRelay настройка человека `webrtcPolicyRelay`.
 * @param verified доказано ли, что весь список указывает на свой узел
 *   ([HearthIceChoice.verified]). Умолчания нет: «проверено» надо предъявить.
 */
fun hearthUseRelay(iceServers: List<*>?, preferRelay: Boolean, verified: Boolean): Boolean =
  if (iceServers.isNullOrEmpty() || !verified) preferRelay else HearthPresets.ALWAYS_RELAY || preferRelay

/**
