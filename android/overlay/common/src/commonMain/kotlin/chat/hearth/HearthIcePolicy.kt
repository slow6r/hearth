/**
 * То же самое, но поверх настроек клиента — чтобы правка в `views/call/WebRTC.kt`
 * была одной строкой и переживала ребейз.
 *
 * `null` возвращается ровно тогда, когда ICE нет вовсе: upstream в этом случае ведёт
 * себя как раньше, а relay-only снимается в [hearthRelayOnlyForCall], иначе звонок не
 * прошёл бы никогда.
 *
 * Не чистая и потому не покрыта commonTest; вся логика, которую есть что проверять,
 * лежит выше, в [hearthPinnedIce], [hearthIceChoice] и [hearthUseRelay].
 */
fun hearthPinnedIceServers(): List<String>? = hearthCurrentIceChoice().servers.ifEmpty { null }

/**
 * Включать ли relay-only на этом звонке — вторая и последняя строка правки в форке.
 *
 * # Почему отдельная функция, а не `hearthUseRelay` прямо из форка
 *
 * Право на relay-only даёт не длина списка, а то, ЧЕЙ это список, и знает об этом
 * только [hearthIceChoice]. Раньше форк звал [hearthUseRelay] с одним лишь списком, и
 * непроверенный список включал relay-only наравне со своим — то есть принуждал медиа
 * идти через чужой сервер. Здесь выбор пересчитывается заново (молча, без повторного
 * предупреждения) и признак [HearthIceChoice.verified] доходит до решения.
 *
 * Пересчёт, а не запомненное с прошлого вызова значение: порядок вызовов в чужом файле
 * — не то, на что стоит опираться, а стоит он копейки.
 *
 * @param iceServers то, что вернул `getIceServers()`: `null` или пусто — звонку нечем
 *   ретранслировать, и relay-only снимается независимо от всего остального.
 */
fun hearthRelayOnlyForCall(iceServers: List<*>?, preferRelay: Boolean): Boolean =
  hearthUseRelay(iceServers, preferRelay, verified = hearthCurrentIceChoice(tell = false).verified)

/**
 * Выбор ICE по текущим настройкам устройства — и побочный эффект «сказать человеку».
 *
 * Строка кладётся туда, где её увидит человек (экран «Узел»), и один раз за сеанс
 * показывается окном: раньше такой случай уходил в `Log.d`, а лог семья не читает.
 *
 * @param tell говорить ли человеку. `false` — для повторного расчёта на том же звонке
 *   ([hearthRelayOnlyForCall]): одно и то же предупреждение дважды подряд не новость,
 *   а шум, и стирать чужую строку вторым проходом тоже незачем.
 */
private fun hearthCurrentIceChoice(tell: Boolean = true): HearthIceChoice {
  val raw = runCatching { ChatController.appPrefs.webrtcIceServers.get() }.getOrNull().orEmpty()
  val bundleHost = HearthPrefs.bundleHost
  val updateHost = runCatching { ChatController.appPrefs.hearthUpdateHost.get() }.getOrNull()
  val choice = hearthIceChoice(
    configured = raw.split("\n"),
    bundleIce = HearthPrefs.bundleIce.orEmpty().split("\n"),
    expectedHost = hearthOwnNodeHost(bundleHost, updateHost),
  )
  if (!tell) return choice
  // Расхождение имён релея и device API само по себе звонки не ломает — с тех пор как
  // источник хоста объявлен явно. Но именно оно раньше ломало их молча, поэтому пусть
  // будет видно: проверка в клиенте надёжнее соглашения между двумя файлами.
  val split = if (hearthNodeHostsAgree(bundleHost, updateHost)) null else HearthIceText.HOSTS_SPLIT
  hearthTellAboutIce(listOfNotNull(choice.notice, split).joinToString("\n\n").ifEmpty { null })
  return choice
}

private fun hearthTellAboutIce(notice: String?) {
  // Здоровый случай стирает старое предупреждение сам: починка обязана быть видна.
  if (notice == null) {
    if (HearthPrefs.iceNotice != null) HearthPrefs.iceNotice = null
    return
  }
  HearthPrefs.iceNotice = notice
  Log.w("hearth", "ICE: $notice")
  // Окно — один раз за сеанс на одну и ту же причину: это настройка телефона, а не
  // событие звонка, и повторять её на каждый звонок значит перестать быть услышанным.
  HearthCallNotice.tell(HearthIceText.ALERT_TITLE, notice, peer = HearthCallNotice.DEVICE)
}
