package chat.hearth

/**
 * Какой способ добычи подписей APK годится для этой версии Android.
 *
 * # Зачем правило вынесено сюда
 *
 * `PackageInfo.signingInfo` и флаг `GET_SIGNING_CERTIFICATES` появились ОБА в API 28,
 * а minSdk у нас 26. В [HearthApkGuard] флаг был проставлен один на все версии, и
 * поле читалось напрямую. На Android 8.0/8.1 это давало `NoSuchFieldError` прямо в
 * момент осмотра уже скачанного файла — то есть приложение падало ровно тогда, когда
 * человек ждал установки. Если бы падение ловили, стало бы не лучше: флаг на API
 * 26-27 не понимается, подписи не запрашиваются, обе стороны сравнения пустые, и
 * [HearthApkRules] честно отвечает отказом. Итог был бы «на Android 8 обновление по
 * воздуху не работает никогда».
 *
 * Правило выбора — арифметика по номеру версии, и её можно прогнать на JVM. Сам
 * вызов `PackageManager` — нельзя, поэтому он остаётся платформенным, а проверяется
 * то, что ломалось: выбор ветки.
 *
 * # Почему на 26-27 не «пропустить»
 *
 * Ветка через `GET_SIGNATURES` обязана давать ТОТ ЖЕ вердикт, а не смягчённый.
 * Нормализация одна и та же — sha256 от байтов сертификата, — поэтому [HearthApkRules]
 * не отличает, откуда набор пришёл, и правило «подписано тем же ключом, что
 * установленное» работает на Android 8 ровно так же, как на Android 9+.
 */
object HearthApkSigningApi {

  /** API 28. Ниже — только `GET_SIGNATURES` и `PackageInfo.signatures`. */
  const val SIGNING_INFO_SINCE: Int = 28

  /** Можно ли читать `PackageInfo.signingInfo`. */
  fun usesSigningInfo(sdkInt: Int): Boolean = sdkInt >= SIGNING_INFO_SINCE

  /**
   * Выбрать одно из двух по версии системы.
   *
   * Обобщённая, чтобы то же правило годилось и для флага запроса, и для названия
   * ветки в тесте: значения обеих констант платформенные, а выбор между ними — нет.
   */
  fun <T> pick(sdkInt: Int, onSigningInfo: T, onLegacySignatures: T): T =
    if (usesSigningInfo(sdkInt)) onSigningInfo else onLegacySignatures
}
