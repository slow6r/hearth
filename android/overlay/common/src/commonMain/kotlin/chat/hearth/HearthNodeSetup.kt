package chat.hearth

import androidx.compose.runtime.mutableStateOf

/**
 * «Телефон не отмечен на узле» — состояние, а не экран.
 *
 * # Что было: локаут после восстановления из архива
 *
 * Восстановление базы из архива приносит профиль и серверы, но НЕ приносит
 * `hearthDeviceId`: преф лежит в настройках устройства, а серверы — в базе. Ветка
 * запуска (`Core.kt`) на каждом старте видела это и переводила приложение в
 * `Step0_HearthImport`, а `App.kt` подменял этим экраном ВЕСЬ интерфейс. Выйти было
 * некуда: ни «позже», ни «пропустить», только поле для кода доступа, которое требует
 * и кода от владельца узла, и доступного узла.
 *
 * Складывалось это со вторым сценарием — «узел недоступен неделю» — в состояние без
 * выхода вовсе: `hearthClaimWithCode` ходит в сеть, узла нет, экран не отпускает.
 * Человек с полностью рабочей базой не видел ни одного чата. Именно уехавший из дома
 * человек с выключившимся домом и получал полную потерю связи.
 *
 * # Правило теперь
 *
 * Приведение к узлу — НЕБЛОКИРУЮЩЕЕ. Человек продолжает читать и писать в
 * существующие чаты; состояние показывается заметной, но закрываемой плашкой над
 * списком чатов (`HearthNodeBanner`), а попытка повторяется в фоне — это делает
 * цепочка приведения (`hearthAfterChatStarted`), которую выход приложения на передний
 * план повторяет, пока она не прошла целиком.
 *
 * # Чем за это платит контур
 *
 * Незаведённое устройство не учтено на узле и потому не отзывается: потерянный
 * телефон отключить нечем. Это настоящая цена, и она названа в тексте плашки. Но
 * альтернатива — запертый человек без связи, и ровно в тот момент, когда связь ему
 * нужнее всего. Отказ оправдан там, где иначе теряется сама защита (чужая подпись
 * обновления, подменённый APK); здесь запрет не защищает ни от чего — он только
 * отнимает переписку, которая уже лежит на устройстве.
 */
object HearthNodeSetup {

  /**
   * Через сколько дней закрытая плашка возвращается.
   *
   * Не «навсегда»: состояние настоящее, и чинить его надо. Не «каждый день»: плашка,
   * которую видно каждый день, закрывают не читая — и тогда она не работает вовсе.
   */
  const val SNOOZE_DAYS: Long = 3

  /**
   * Устройство не заведено на узле.
   *
   * Пишется [hearthNoteNodeSetup] — после запуска чата и при каждом выходе приложения
   * на передний план. Читает плашка.
   */
  val notOnNode = mutableStateOf(false)

  /**
   * День, когда плашку закрыли. `null` — не закрывали.
   *
   * Продублировано в состоянии Compose, а не читается из настроек при каждой
   * перерисовке: иначе закрытие плашки не перерисовало бы список чатов.
   */
  val dismissedDay = mutableStateOf<Long?>(null)

  /** Прочитать отметку из настроек один раз за жизнь процесса. */
  fun load() {
    if (loaded) return
    loaded = true
    dismissedDay.value = runCatching { HearthPrefs.nodeNoticeSnoozeDay }.getOrNull()
  }

  /** Человек закрыл плашку. Вернётся через [SNOOZE_DAYS]. */
  fun dismiss(today: Long = hearthNowEpochDays()) {
    dismissedDay.value = today
    runCatching { HearthPrefs.nodeNoticeSnoozeDay = today }
  }

  /**
   * Устройство заведено — забыть и состояние, и отметку закрытия.
   *
   * Отметку тоже: иначе следующая потеря настроек три дня не показывала бы плашку,
   * потому что «её уже когда-то закрывали».
   */
  fun done() {
    notOnNode.value = false
    dismissedDay.value = null
    loaded = true
    runCatching { HearthPrefs.nodeNoticeSnoozeDay = null }
  }

  @Volatile
  private var loaded = false
}

/**
 * Показывать ли плашку. Чистое правило — чтобы его можно было прогнать на JVM.
 *
 * @param notOnNode устройство не заведено на узле.
 * @param dismissedDay день, когда плашку закрыли, или `null`.
 * @param today сегодняшний день в днях эпохи.
 *
 * Часы, переведённые НАЗАД (`today < dismissedDay`), показывают плашку: иначе одна
 * неверная дата спрятала бы её на годы вперёд.
 */
fun hearthNodeBannerVisible(
  notOnNode: Boolean,
  dismissedDay: Long?,
  today: Long,
  snoozeDays: Long = HearthNodeSetup.SNOOZE_DAYS,
): Boolean {
  if (!notOnNode) return false
  val dismissed = dismissedDay ?: return true
  if (today < dismissed) return true
  return today - dismissed >= snoozeDays
}

/**
 * Тексты плашки и экрана подключения.
 *
 * Собраны здесь, а не по месту показа, по той же причине, что и [HearthOnboardingText]:
 * весь текст сборки должен читаться в одном файле.
 */
object HearthNodeText {

  const val BANNER_TITLE = "Телефон не подключён к домашнему узлу"

  /**
   * Первая фраза — самая важная: связь работает.
   *
   * Человек видит незнакомую плашку в приложении, которым он пользуется каждый день.
   * Если не сказать сразу, что всё в порядке, он решит, что сломалось, и начнёт
   * чинить — чаще всего переустановкой, то есть потерей переписки.
   */
  const val BANNER_BODY =
    "Чаты, сообщения и звонки работают как обычно. Но этот телефон не отмечен на " +
      "узле: он не будет получать обновления, а если потеряется — его нельзя будет " +
      "отключить. Подключите, когда под рукой будет код доступа."

  const val BANNER_CONNECT = "Подключить к узлу"

  /** Подпись кнопки закрытия. Плашка вернётся через [HearthNodeSetup.SNOOZE_DAYS] дней. */
  const val BANNER_LATER = "Позже"

  /**
   * Заголовок экрана подключения, когда переписка на телефоне УЖЕ есть.
   *
   * Отдельно от [HearthOnboardingText.CODE_TITLE] намеренно. Тот же экран в этом
   * случае видит не новый человек, а старый, у которого приложение вдруг спросило
   * код: восстановление из архива, очистка данных приложения системой. Заголовок
   * «Код доступа» посреди рабочего дня читается как «приложение забыло всё».
   */
  const val RESTORED_TITLE = "Подключение к узлу"

  const val RESTORED_BODY =
    "Переписка на месте, приложение ничего не забыло. Не хватает только отметки на " +
      "домашнем узле — её не было в резервной копии. Введите код доступа, который " +
      "вам дадут, или вернитесь к чатам и сделайте это позже."

  /** Выход с экрана подключения обратно к чатам. */
  const val RESTORED_LATER = "Позже, к чатам"
}
