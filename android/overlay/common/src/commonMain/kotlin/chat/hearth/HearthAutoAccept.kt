package chat.hearth

/**
 * Что телефон забирает с узла сам, не спрашивая.
 *
 * # Что было видно людям
 *
 * «У меня стикеры нормальные, у собеседника мыльные». Так и есть, и дело не в стикерах.
 *
 * Картинка уходит двумя частями: внутри сообщения едет превью, а сам файл лежит на
 * XFTP-узле и качается отдельно. Превью по бюджету upstream — 14 КБ
 * (`resizeImageToStrSize`), и для стикера 512×512 с прозрачностью это PNG примерно
 * 128×128: на экране мыло. ОТПРАВИТЕЛЬ мыла не видит никогда — у него лежит исходный
 * файл, и он показывает его. Получатель видит превью до тех пор, пока файл не скачается.
 *
 * То есть «мыльные» означает ровно одно: файл у получателя так и не скачался.
 *
 * # Почему он не скачивался
 *
 * У upstream автоприём файла привязан к одному выключателю — «принимать изображения»
 * (`privacyAcceptImages`). Выключатель этот про осторожность: не тянуть молча
 * многомегабайтные картинки от кого попало, да ещё и обращаясь за ними к файловому
 * релею. Выключен он — и картинка ждёт нажатия. Стикер при этом ждёт нажатия на мыло,
 * которое на мыло и похоже, так что нажимать никто не догадывается.
 *
 * # Почему для маленьких картинок выключатель можно обойти
 *
 * Оба довода за осторожность у нас не работают.
 *
 * Трафик: стикер весит 20–45 КБ (замерено по набору на узле), а потолок здесь — 128 КБ.
 * Это меньше, чем весит само сообщение с превью и подписью у многих фотографий.
 *
 * Метаданные: у upstream файловый релей — чужой сервер, и обращение к нему сообщает
 * третьей стороне, что вы получили файл. У нас XFTP — это наш же узел, с которым телефон
 * и так держит постоянное соединение ради доставки сообщений (ТЗ §8.2 п.4). Запрос файла
 * не добавляет наблюдателю ни одного нового факта — тот же довод, которым ADR 0010
 * оправдывает проверку обновлений с узла.
 *
 * Поэтому потолок, а не отмена выключателя: он продолжает работать для всего, что крупнее.
 * Человек, выключивший «принимать изображения», по-прежнему не получит молча фотографию
 * на пару мегабайт — он получит только то, что меньше потолка.
 */
object HearthAutoAccept {

  /**
   * Потолок «маленькой картинки».
   *
   * 128 КБ — втрое больше самого тяжёлого стикера в наборе (45 КБ) и втрое меньше
   * `MAX_IMAGE_SIZE` upstream (255 КБ), до которого сжимаются обычные фотографии. То
   * есть под правило попадают стикеры и мелкая графика, но не фотографии: у них свой
   * путь, через выключатель.
   */
  const val SMALL_IMAGE_MAX_BYTES: Long = 128 * 1024

  /**
   * Забирать ли картинку, даже если «принимать изображения» выключено.
   *
   * `isImage` приходит снаружи, а не выводится здесь: тип содержимого сообщения живёт в
   * модели upstream, и тащить её в overlay означало бы привязать правило к чужому
   * перечислению, которое меняется между тегами.
   *
   * `fileSize` нуллабелен намеренно: у сообщения может не быть файла вовсе, и это «нет»,
   * а не «ноль байт».
   */
  fun acceptsSmallImageAnyway(isImage: Boolean, fileSize: Long?): Boolean {
    if (!isImage) return false
    val size = fileSize ?: return false
    if (size <= 0L) return false
    return size <= SMALL_IMAGE_MAX_BYTES
  }
}
