package chat.hearth

/**
 * Работает ли чат — из трёх состояний, а не из двух.
 *
 * # Зачем отдельное место
 *
 * `chatModel.chatRunning` — это `Boolean?`, и значений у него ТРИ:
 *
 *   * `null`  — ядро ещё ни разу не запускали в этом процессе;
 *   * `true`  — запущено;
 *   * `false` — остановлено человеком.
 *
 * Upstream местами пишет `chatRunning.value == false`, и тогда `null` молча
 * попадает в ветку «работает»: сравнение неравно, значит «не остановлен». На свежей
 * установке это выглядело так, что в настройках стоит «чат запущен», а на самом деле
 * ядро не стартовало — человек видел галочку и не понимал, почему ничего не ходит.
 * Лечилось только ручным выключить/включить, то есть случайным попаданием.
 *
 * Тот же upstream в других местах пишет правильно (`== true`, `!= true`) и даже
 * проверяет `null` отдельным экраном «загрузка чатов». То есть это не соглашение, а
 * расхождение внутри одного кода — и оно вернётся при следующем ребейзе на новый тег.
 *
 * Поэтому правило вынесено сюда и покрыто тестом: если ребейз принесёт `== false`
 * обратно, конфликт будет виден на вызове, а тест скажет, чего именно лишились.
 *
 * # Правило
 *
 * Показывать «работает» только тогда, когда это ТОЧНО так. Неизвестность
 * приравнивается к «не работает»: неверно сказать человеку, что всё в порядке,
 * когда мы не знаем, хуже, чем лишний раз показать «остановлен».
 */
object HearthChatState {

  /** Ядро точно запущено. `null` — нет: мы этого не знаем. */
  fun isRunning(flag: Boolean?): Boolean = flag == true

  /**
   * Ядро не работает — остановлено или ещё не запускалось.
   *
   * Именно это значение показывают экраны настроек и им же гасят действия, которые
   * без работающего ядра всё равно не выполнятся.
   */
  fun isStopped(flag: Boolean?): Boolean = flag != true
}
