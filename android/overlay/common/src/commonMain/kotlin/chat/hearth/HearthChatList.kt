package chat.hearth

/**
 * Список чатов без дублей.
 *
 * # Откуда дубли
 *
 * У `ChatModel.chatsContext.addChat` нет проверки: это голый `chats.add(0, chat)`,
 * а вызывающих у него двенадцать. Список при этом пересобирается целиком ещё и при
 * каждом выходе приложения на передний план (`SimplexApp`, ON_START → `apiGetChats` →
 * `replaceAll`). Гонка между двумя корутинами выглядит так:
 *
 *   1. приёмник сообщений: `hasChat(@2)` → false (список ещё старый или пустой);
 *   2. главный поток: `replaceAll(новый список, в нём уже есть @2)`;
 *   3. приёмник: `addChat(@2)` → второй `@2`.
 *
 * Дальше `LazyColumn` с ключом `(remoteHostId, id)` встречает два одинаковых ключа
 * и роняет приложение: `Key "(null, @2)" was already used`. Именно этот стек и
 * прислали из семьи. Сценарий особенно вероятен на Huawei: система убивает фоновую
 * службу, а при открытии приложения накопившиеся события приходят залпом — ровно в
 * тот момент, когда список пересобирается.
 *
 * # Правило
 *
 * Ключ — пара `(remoteHostId, id)`, как у `LazyColumn`. При совпадении остаётся
 * ПЕРВОЕ вхождение: в `replaceAll` первым идёт то, что пришло из базы, а при
 * `addChat` существующая запись уже не хуже добавляемой — обе описывают один чат,
 * и у существующей могут быть счётчики непрочитанного, которых у новой нет.
 */
object HearthChatList {

  /** Оставить по одному элементу на ключ, сохранив порядок первых вхождений. */
  fun <T> dedupe(items: List<T>, key: (T) -> Any?): List<T> {
    if (items.size < 2) return items
    val seen = HashSet<Any?>(items.size)
    val out = ArrayList<T>(items.size)
    for (item in items) {
      if (seen.add(key(item))) out.add(item)
    }
    return if (out.size == items.size) items else out
  }
}
