package chat.hearth

/**
 * Переподключение к релеям при выходе приложения на передний план — но не чаще
 * раза в минуту.
 *
 * # Зачем
 *
 * Жалоба из семьи: «сообщения приходят, потом перестают, помогает только выключить
 * и включить „чат запущен“». Выключить/включить — это `apiStopChat` + `apiStartChat`,
 * то есть заново подписаться на все очереди. Значит подписки теряются и сами не
 * восстанавливаются. Причин две, и обе подтверждены: Wi-Fi в доме рвётся из-за
 * перегруженного 2.4 ГГц, а на Huawei система убивает фоновую службу.
 *
 * Мягкий аналог выключить/включить — `reconnectAllServers`: ядро переустанавливает
 * соединения и подписки, не останавливая чат. Upstream зовёт его только при смене
 * сети. Здесь он зовётся ещё и при каждом выходе на передний план: именно в этот
 * момент человек ждёт сообщений и замечает, что их нет.
 *
 * # Почему с ограничением
 *
 * Выход на передний план случается и десять раз в минуту — переключение между
 * приложениями. Переподключать все релеи на каждое — это шторм соединений на узел и
 * лишний расход батареи. Минута — достаточно редко, чтобы не мешать, и достаточно
 * часто, чтобы «открыл — и сообщения пришли» работало.
 */
object HearthResume {

  const val MIN_GAP_MS: Long = 60_000

  @Volatile
  private var lastReconnectMs: Long = 0

  /** Чистое правило: пора ли переподключаться, если последний раз был в [lastMs]. */
  fun shouldReconnect(lastMs: Long, nowMs: Long, minGapMs: Long = MIN_GAP_MS): Boolean =
    lastMs == 0L || nowMs - lastMs >= minGapMs || nowMs < lastMs

  /** Отметить попытку, если по правилу пора; вернуть, пора ли. */
  fun claim(nowMs: Long): Boolean {
    if (!shouldReconnect(lastReconnectMs, nowMs)) return false
    lastReconnectMs = nowMs
    return true
  }

  /** Для тестов и для сброса при остановке чата. */
  fun reset() {
    lastReconnectMs = 0
  }
}
