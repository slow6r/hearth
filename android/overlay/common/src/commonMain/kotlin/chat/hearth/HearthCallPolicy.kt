package chat.hearth

import chat.simplex.common.platform.Log
import chat.simplex.common.views.helpers.AlertManager

/**
 * Прикладной AES поверх звонка: политика форка (пункт 3.3 аудита, CALL-3/CALL-4).
 *
 * # Что делает upstream
 *
 * Ядро решает, шифровать ли звонок дополнительным слоем, по возможностям собеседника
 * (`Call.hs: encryptedCall`). Если собеседник объявил `capabilities.encryption = false`
 * — старая сборка, WebView без insertable streams, намеренно изменённый клиент, —
 * общий ключ не вырабатывается, и ядро честно сообщает наверх `askConfirmation = true`.
 * Kotlin этот флаг не читает вообще (в `SimpleXAPI.kt` на его месте стоит
 * upstream-овское `// TODO askConfirmation?`), а `sharedKey = null` передаёт дальше
 * молча. Единственное следствие для человека — строка «нет e2e-шифрования» на экране
 * звонка, то есть надпись, а не решение.
 *
 * # Почему это нельзя просто запретить
 *
 * Точка, где принимается решение «шифровать или нет», живёт в Haskell-ядре, а ядро в
 * Android-сборке — двоичный файл из официального APK upstream: его sha256 пинован
 * (`scripts/native-libs.sha256`) и сверяется релизным гейтом. Пересобрать ядро — это
 * отдельная большая работа с переписью гейта (android/FORK.md, «Чего в форке нет»).
 * Значит на Android прикладной AES обязателен только в наших руках — выше ядра, в
 * клиенте. Для чужого клиента, который в контур вообще не попадает, это не запрет.
 * Поэтому более ценный контроль здесь — пин ICE (HearthIcePolicy.kt), а не этот.
 *
 * # Почему флаг выключен
 *
 * Включённый запрет ломает звонки со ВСЕМИ уже установленными сборками (h17…h21) и
 * с любым WebView без insertable streams. Это приложение стоит у семьи; «звонки
 * перестали работать» без объяснения — хуже, чем звонок с предупреждением. Поэтому
 * выкатывается выключенным, а включается отдельным релизом — после того как по
 * списку устройств узла видно, что версия у всех одна.
 */
object HearthCallPolicy {

  /**
   * Требовать прикладной AES безусловно.
   *
   * `false` — этап 1: клиент предупреждает, но соединяет. `true` — этап 2: клиент
   * отказывается. Менять только вместе с раскаткой на все устройства семьи.
   */
  const val REQUIRE_APP_AES = false
}

/** Что делать со звонком, у которого нет прикладного AES. */
sealed interface HearthCallDecision {

  /**
   * Что показать человеку. У обычного звонка причины нет.
   *
   * Свойство объявлено на интерфейсе, а не на двух ветках порознь, именно чтобы
   * вызывающий не мог взять причину, не разобрав случай, и чтобы её нельзя было
   * забыть показать.
   */
  val reason: String?

  /** Оба слоя на месте, звонок обычный. */
  data object Allow : HearthCallDecision {
    override val reason: String? = null
  }

  /**
   * Слоя нет, но звонок разрешён. [reason] показывается человеку явно — это и есть
   * «явный сигнал в интерфейсе» вместо тихой строки статуса на экране звонка.
   */
  data class Warn(override val reason: String) : HearthCallDecision

  /**
   * Слоя нет, звонок не состоится. [reason] показывается человеку.
   *
   * В сегодняшней сборке этот случай не возникает: [hearthCallDecision] строит
   * `Refuse` только при `mandatory = true`, а [HearthCallPolicy.REQUIRE_APP_AES]
   * выключен. Это не мёртвая ветка, а выключенный этап 2, и включается он правкой
   * одной константы — поэтому проверен он должен быть заранее, а не в день
   * включения: HearthCallPolicyTest гоняет оба значения `mandatory`, и отдельным
   * тестом закреплено, что при `false` `Refuse` не появляется НИ при одном сочетании
   * входов. Единственное место, где `Refuse` что-то меняет для человека, —
   * [hearthTellAboutCall]: там он показывается всегда и с припиской, что звонка не
   * будет.
   */
  data class Refuse(override val reason: String) : HearthCallDecision
}

/**
 * Решение по одному звонку.
 *
 * @param localEncryption умеет ли шифровать НАША сторона (`capabilities.encryption`
 *   из ответа WebView). На WebView без insertable streams — `false`.
 * @param sharedKey общий ключ прикладного слоя из ответа ядра. `null` — слоя нет.
 * @param askConfirmation флаг ядра «шифрование понижено»: мы просили зашифрованный
 *   звонок, собеседник не смог. Читаем его, потому что `sharedKey != null` бывает и
 *   при понижении — молча глотать такой звонок нельзя.
 * @param mandatory см. [HearthCallPolicy.REQUIRE_APP_AES]; параметром — чтобы оба
 *   режима проверялись тестом, а не только тот, что включён сегодня.
 *
 * Чистая функция: ни платформы, ни модели upstream, чтобы её можно было прогнать на JVM.
 */
fun hearthCallDecision(
  localEncryption: Boolean,
  sharedKey: String?,
  askConfirmation: Boolean = false,
  mandatory: Boolean = HearthCallPolicy.REQUIRE_APP_AES,
): HearthCallDecision {
  val reason = when {
    !localEncryption ->
      "Этот телефон не умеет шифровать звонки дополнительным слоем: системный WebView слишком старый."
    sharedKey == null ->
      "У собеседника нет дополнительного слоя шифрования звонка — скорее всего, у него старая версия приложения."
    askConfirmation ->
      "Собеседник не смог подтвердить дополнительный слой шифрования: звонок защищён слабее обычного."
    else -> return HearthCallDecision.Allow
  }
  return if (mandatory) HearthCallDecision.Refuse(reason) else HearthCallDecision.Warn(reason)
}

/**
 * Решение по одной только НАШЕЙ стороне.
 *
 * Нужно там, где собеседник ещё не ответил: WebView сообщает свои возможности до
 * того, как отправлено приглашение (`WCallResponse.Capabilities`), и молчать об
 * устаревшем WebView до конца переговоров незачем — человек узнает раньше и на
 * понятном ему шаге.
 *
 * Общий ключ здесь подставляется непустым намеренно: в этой точке его ещё нет и быть
 * не может, а проверяют его там, где он реально приходит, — в обработчике
 * `CR.CallOffer` (исходящий звонок) и в `CallManager` (входящий).
 */
fun hearthLocalCallDecision(
  localEncryption: Boolean,
  mandatory: Boolean = HearthCallPolicy.REQUIRE_APP_AES,
): HearthCallDecision =
  hearthCallDecision(localEncryption, sharedKey = KEY_CHECKED_ELSEWHERE, mandatory = mandatory)

/**
 * Заглушка общего ключа для [hearthLocalCallDecision].
 *
 * Значение не сравнивается ни с чем — важно только, что оно не `null`.
 */
private const val KEY_CHECKED_ELSEWHERE = "ключ проверяется в другом месте"

/**
 * Одно предупреждение на собеседника за сеанс работы приложения.
 *
 * # Что было и почему так нельзя
 *
 * Память была на одну пару «звонок + причина». Пока в семье стоят сборки h17–h21,
 * `sharedKey` у них пуст ВСЕГДА, значит причина одна и та же, а идентификатор звонка
 * каждый раз новый — и окно всплывало на КАЖДЫЙ звонок с этими телефонами. Окно,
 * которое видно каждый раз, перестают читать; а при `REQUIRE_APP_AES = false` это
 * окно и есть весь эффект проверки. То есть проверка обнуляла сама себя.
 *
 * Вдобавок память на ОДНУ пару означала, что чередование двух разных причин внутри
 * одного звонка окно повторяло: причина сменилась — совпадения нет — говорим снова.
 *
 * # Правило теперь
 *
 * Ключ — собеседник плюс причина, а память живёт до перезапуска приложения. Значит
 * про один и тот же изъян одного и того же собеседника скажут один раз за сеанс, а
 * три точки проверки внутри звонка (свои возможности, приглашение, ответ) по-прежнему
 * не повторяются. Хранится набор, а не последнее значение, поэтому чередование причин
 * ничего не воскрешает.
 *
 * Отказ (`Refuse`) этой памятью НЕ глушится: см. [hearthTellAboutCall]. Молчаливо
 * завершённый звонок человек воспринимает как поломку приложения.
 */
object HearthCallNotice {

  /** Ключ для предупреждений про сам телефон, а не про собеседника. */
  const val DEVICE = "это устройство"

  /**
   * Потолок памяти.
   *
   * Набор растёт по одному на «собеседник + причина», то есть в семье это единицы
   * записей. Потолок стоит не ради памяти, а чтобы неограниченный рост был невозможен
   * в принципе: переполнение просто начинает сеанс заново.
   */
  private const val LIMIT = 64

  @Volatile
  private var told: Set<String> = emptySet()

  /**
   * `true` — про ЭТУ причину ЭТОМУ собеседнику в этом сеансе ещё не говорили.
   *
   * @param peer идентификатор собеседника (`Contact.id`) либо [DEVICE]. `null` —
   *   собеседник неизвестен; тогда ключом остаётся одна причина, и сказать о ней
   *   всё равно надо не больше раза за сеанс.
   */
  fun shouldTell(peer: String?, reason: String): Boolean {
    val key = (peer ?: "?") + "\u0000" + reason
    if (key in told) return false
    // Копия набора, а не изменение на месте: без блокировок гонка двух звонков может
    // максимум продублировать окно, а не испортить набор. Блокировка на пути звонка
    // стоила бы дороже, чем лишнее окно раз в год.
    told = (if (told.size >= LIMIT) emptySet() else told) + key
    return true
  }

  /**
   * Сказать человеку, если про это ещё не говорили.
   *
   * @param force показать несмотря на память. Ставится там, где иначе человек не
   *   узнает, почему действие не состоялось.
   * @return показали ли окно.
   */
  fun tell(title: String, message: String, peer: String?, force: Boolean = false): Boolean {
    if (!force && !shouldTell(peer, message)) return false
    AlertManager.shared.showAlertMsg(title, message)
    return true
  }

  /**
   * Забыть всё, о чём уже сказали.
   *
   * Зовут из `views/database/DatabaseView.kt`, из двух мест: при остановке чата
   * (`stopChatAsync`) и сразу после восстановления базы из архива. Оба раза память
   * перестаёт что-либо значить, а во втором случае ещё и начинает врать: ключ здесь
   * — `Contact.id`, а в восстановленной базе тот же идентификатор принадлежит уже
   * другому человеку, и старая запись молча съела бы предупреждение о НЁМ. Из
   * продуктового кода больше ниоткуда: память и задумана на весь сеанс работы
   * приложения.
   *
   * Тесты зовут её же — глобальный объект иначе не изолировать (HearthCallPolicyTest).
   */
  fun forget() {
    told = emptySet()
  }
}

/**
 * Применить решение к звонку: сказать человеку и ответить, можно ли продолжать.
 *
 * Это и есть «явный сигнал в интерфейсе» вместо строки статуса: окно, которое надо
 * закрыть руками, человек видит, а надпись под именем собеседника — нет.
 *
 * @param peer идентификатор собеседника (`Contact.id`), а НЕ идентификатор звонка:
 *   изъян принадлежит собеседнику и не меняется от звонка к звонку, поэтому и
 *   говорить о нём надо раз на собеседника, а не раз на звонок.
 * @return `false` — звонок продолжать нельзя, вызывающий обязан его завершить. При
 *   [HearthCallPolicy.REQUIRE_APP_AES] `= false` это не возвращается никогда: см.
 *   [hearthCallDecision], где при `mandatory = false` вместо `Refuse` строится `Warn`.
 *
 * Не чистая (ходит в [AlertManager]) и потому не покрыта commonTest; вся логика,
 * которую есть что проверять, лежит в [hearthCallDecision] и [HearthCallNotice].
 */
fun hearthApplyCallDecision(
  peer: String?,
  localEncryption: Boolean,
  sharedKey: String?,
  askConfirmation: Boolean = false,
): Boolean = hearthTellAboutCall(peer, hearthCallDecision(localEncryption, sharedKey, askConfirmation))

/** То же, но по одним лишь своим возможностям. См. [hearthLocalCallDecision]. */
fun hearthApplyLocalCallDecision(peer: String?, localEncryption: Boolean): Boolean =
  hearthTellAboutCall(peer, hearthLocalCallDecision(localEncryption))

private fun hearthTellAboutCall(peer: String?, decision: HearthCallDecision): Boolean {
  val reason = decision.reason ?: return true
  val refused = decision is HearthCallDecision.Refuse
  Log.w("hearth", "звонок без прикладного слоя шифрования: $reason")
  HearthCallNotice.tell(
    title = if (refused) HearthCallText.REFUSED_TITLE else HearthCallText.ALERT_TITLE,
    // При отказе к причине дописывается ГЛАВНОЕ — что звонка не будет и что с этим
    // делать. Раньше текст был тот же, что при предупреждении, и человек видел окно
    // «защищён слабее обычного», после которого звонок просто обрывался.
    message = if (refused) reason + "\n\n" + HearthCallText.REFUSED_BODY else reason,
    peer = peer,
    // Отказ показывается ВСЕГДА: звонок, оборвавшийся молча, выглядит как поломка
    // приложения, и чинить его будут переустановкой.
    force = refused,
  )
  return !refused
}

/**
 * Тексты про звонки, которые видит человек.
 *
 * Собраны здесь, а не по месту показа, по той же причине, что и
 * [HearthOnboardingText]: правки в дереве форка должны быть в одну строку и пережить
 * ребейз, а весь текст сборки — читаться в одном файле.
 */
object HearthCallText {

  /** Заголовок окна о звонке без прикладного AES. */
  const val ALERT_TITLE = "Звонок защищён слабее обычного"

  /** Заголовок окна, когда звонок ОТКЛОНЁН (см. [HearthCallPolicy.REQUIRE_APP_AES]). */
  const val REFUSED_TITLE = "Звонок не состоится"

  /**
   * Что дописывается к причине при отказе.
   *
   * Без этой строки человек видел ровно то же окно, что при обычном предупреждении, а
   * звонок при этом обрывался. «Почему не идёт совсем» — это и есть то единственное,
   * что ему нужно знать: иначе он решит, что сломалось приложение.
   */
  const val REFUSED_BODY =
    "Поэтому звонок сейчас не состоится. Обновите приложение на обоих телефонах — " +
      "после этого звонки заработают. Переписка работает как обычно."

  /**
   * Почему список ICE нельзя править руками (см. [HearthPresets.ICE_EDITABLE]).
   *
   * Человеку говорится не «нельзя», а ЧТО происходит вместо этого: серверы для
   * звонков приходят с узла и обновляются сами. Запрет без объяснения выглядит
   * поломкой, и его начинают обходить.
   */
  const val ICE_LOCKED =
    "Серверы для звонков задаёт домашний узел: они приходят вместе с настройками и " +
      "обновляются сами. Правка списка вручную увела бы звонок через чужой сервер, " +
      "которому видны адреса обоих собеседников."

  /**
   * Почему переключатель «всегда через ретранслятор» недоступен
   * (см. [HearthPresets.ALWAYS_RELAY]).
   */
  const val RELAY_LOCKED =
    "Звонки всегда идут через ретранслятор домашнего узла — так собеседник не видит " +
      "адрес вашего устройства. Выключить это нельзя: настройку выключают «чтобы " +
      "позвонить» и обратно не включают."
}
