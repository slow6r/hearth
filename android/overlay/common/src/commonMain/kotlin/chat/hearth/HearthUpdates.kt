package chat.hearth

/**
 * Тихая проверка обновлений из общего кода запуска.
 *
 * # Зачем понадобилось expect/actual
 *
 * Сама проверка ([HearthUpdates.checkQuietly]) живёт в androidMain: ей нужен
 * `Context` — и для канала уведомлений, и для пинованного ключа релиза. А фоновый
 * блок запуска, куда её надо позвать, лежит в `platform/Core.kt`, то есть в общем
 * коде: настольная сборка компилирует тот же файл. Прямой вызов из commonMain не
 * собрался бы для desktop, и «проверка есть, но её никто не зовёт» осталась бы
 * ровно тем же недостатком, что и раньше.
 *
 * Поэтому правка в дереве форка — одна строка, а разница платформ спрятана здесь,
 * тем же приёмом, что у [hearthRefreshIceServers].
 */
expect suspend fun hearthCheckUpdatesQuietly()

/**
 * Говорить ли человеку в шторку, что на узле есть новая версия.
 *
 * # Зачем понадобилось отдельное правило
 *
 * Проверка при запуске нашла новую версию и клала строку на экран «Домашний узел» —
 * туда, куда по своей воле не заходят. В шторку уходили только неустранимые отказы и
 * молчание узла, то есть человек узнавал о СЛОМАННОМ обновлении, но не о доступном.
 * Практически это означало, что §1.4 («security-релиз в контуре за ≤ 7 дней») держался
 * на том, вспомнит ли кто-нибудь открыть настройки.
 *
 * # Почему счётчик по версии, а не по дню
 *
 * У [HearthUpdates.warnIfSilent] и [HearthUpdates.warnAboutRefusal] поводы длящиеся:
 * узел молчит или ключа нет, и напоминать о них чаще раза в окно — значит приучить не
 * читать. Здесь повод другой: он не длится, а СМЕНЯЕТСЯ. Вышла версия новее той, о
 * которой уже сказали, — это новость, и ждать конца окна нельзя: именно в эту разницу
 * попадает security-релиз, выпущенный через день после обычного.
 *
 * Поэтому помним не только день, но и какой versionCode уже объявляли. Сменился —
 * говорим сразу; тот же самый — не чаще раза за окно.
 *
 * # Часы назад
 *
 * Если день на телефоне оказался РАНЬШЕ записанного, разность отрицательна и обычная
 * проверка «прошло ли окно» замолчала бы до тех пор, пока часы не догонят — на год
 * вперёд переведённые часы означали бы год тишины. Считаем это поводом сказать: лучше
 * лишнее уведомление, чем пропущенный security-релиз.
 */
object HearthUpdateOffer {

  const val TITLE: String = "Очаг: есть новая версия"

  fun shouldAnnounce(
    versionCode: Int,
    announcedVersionCode: Long?,
    announcedDay: Long?,
    todayEpochDays: Long,
    repeatAfterDays: Long = HearthUpdateTrust.STALE_AFTER_DAYS,
  ): Boolean {
    if (announcedVersionCode != versionCode.toLong()) return true
    if (announcedDay == null) return true
    if (todayEpochDays < announcedDay) return true
    return todayEpochDays - announcedDay >= repeatAfterDays
  }

  /**
   * Текст уведомления.
   *
   * Прямо сказано, что само оно не скачается: [HearthUpdates.checkQuietly] намеренно не
   * качает APK — сотни мегабайт по мобильной сети без спроса это счёт за трафик, а не
   * забота. Без этой фразы «есть новая версия» читается как «оно уже ставится».
   */
  fun text(versionName: String): String =
    "На узле готова версия $versionName. Откройте «Настройки → Домашний узел» и нажмите " +
      "«Проверить обновление»: приложение скачает её и предложит установить. Само оно не " +
      "качает — обновление весит сотни мегабайт, и тратить на него мобильный трафик без " +
      "спроса неправильно."
}
