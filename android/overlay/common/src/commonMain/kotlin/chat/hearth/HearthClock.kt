package chat.hearth

import kotlinx.datetime.Clock
import kotlinx.datetime.Instant

/**
 * Часы и разбор отметок времени — одним местом на весь оверлей.
 *
 * # Почему отдельный файл
 *
 * Свежесть проверяется в трёх разных местах (манифест обновления, креды TURN, QR
 * узла), и раньше каждое обходилось своими средствами: манифест сравнивал СТРОКИ,
 * креды и QR не сравнивали ничего. Сравнение строк ломается молча: отметка
 * `2026-09-12T11:00:00+03:00` лексикографически МЕНЬШЕ, чем `2026-09-12T08:00:00Z`,
 * хотя описывает тот же момент. Такой промах выглядит не как ошибка, а как «узел
 * почему-то отдаёт старый манифест».
 *
 * # Чего эти часы НЕ дают
 *
 * Доверенного времени на устройстве нет: человек переводит часы руками, а
 * захваченный узел про это знает. Поэтому календарные правила здесь — это подсказка
 * («похоже, дата на телефоне не та»), а не доказательство. Правило, на которое можно
 * опереться при переведённых часах, — только ПРОШЕДШИЙ локальный интервал: сколько
 * телефон уже прожил с одной и той же отметкой. Сдвиг часов назад такое правило не
 * обходит, а лишь откладывает.
 */
const val HEARTH_SECONDS_PER_DAY: Long = 86_400L

/**
 * Деление с округлением вниз.
 *
 * Своё, а не `Math.floorDiv`: это commonMain, платформенных классов здесь нет. Для
 * отрицательных секунд эпохи (дата раньше 1970 — переведённые часы такое дают)
 * обычное деление округляет к нулю, и день получился бы на единицу больше.
 */
internal fun hearthFloorDiv(value: Long, divisor: Long): Long {
  val q = value / divisor
  return if (value % divisor != 0L && (value xor divisor) < 0L) q - 1 else q
}

/** Текущий момент в секундах эпохи. Отдельная функция, чтобы тесты подставляли своё. */
fun hearthNowEpochSeconds(): Long = Clock.System.now().epochSeconds

/** Сегодняшний день в днях эпохи (UTC). */
fun hearthNowEpochDays(): Long = hearthFloorDiv(hearthNowEpochSeconds(), HEARTH_SECONDS_PER_DAY)

/**
 * Текущий момент в миллисекундах эпохи.
 *
 * Нужен там, где считают КОРОТКИЕ промежутки — например, «не чаще раза в четверть
 * часа» ([HearthStartup]). Секунд для этого хватило бы, но миллисекунды здесь уже в
 * ходу (`HearthResume`), а два разных масштаба времени в соседних файлах однажды
 * перепутают.
 */
fun hearthNowEpochMillis(): Long = hearthNowEpochSeconds() * 1000L

/**
 * Разобрать отметку времени RFC 3339 в секунды эпохи.
 *
 * `null` — разобрать не удалось. Вызывающий обязан считать это отказом, а не «ну и
 * ладно»: неразобранная отметка — это отсутствие проверки, ради которой её и ввели.
 * Дополнительно принимается целое число секунд эпохи: так отдают срок годности
 * некоторые серверные реализации, и падать на этом было бы жёстче, чем нужно.
 */
fun hearthEpochSecondsOf(timestamp: String?): Long? {
  val text = timestamp?.trim().orEmpty()
  if (text.isEmpty()) return null
  text.toLongOrNull()?.let { return it }
  return runCatching { Instant.parse(text).epochSeconds }.getOrNull()
}

/** То же в днях эпохи: календарные правила считаются днями, а не секундами. */
fun hearthEpochDaysOf(timestamp: String?): Long? =
  hearthEpochSecondsOf(timestamp)?.let { hearthFloorDiv(it, HEARTH_SECONDS_PER_DAY) }
