package chat.hearth

/**
 * Потолок объёма при загрузке APK с узла.
 *
 * # Зачем
 *
 * Потолки стояли на всём, что читается в память (манифест, bundle, стикер), а на
 * поток, который пишется на диск, — нет: цикл качал до EOF. Рассуждение было такое:
 * узел свой, а sha256 всё поймает. Оба довода не выдерживают модели угроз этого
 * модуля — она прямо допускает ЗАХВАЧЕННЫЙ узел. Захваченный узел отдаёт поток любой
 * длины, и телефон забивает внутреннюю память, выглядя при этом штатно:
 * foreground-сервис, уведомление «Загрузка Очага», проценты. Хеш проверяется после
 * того, как всё записано, то есть после того, как место кончилось.
 *
 * Отдельно про докачку: недокачанный файл ОБЯЗАН удаляться при срабатывании потолка.
 * Иначе следующий заход просит остаток через `Range` и набирает тот же объём по
 * частям — потолок обходится не хитростью, а терпением.
 *
 * Отдельно про ЧУЖОЙ остаток: недокачанное от прошлой версии (отменили, не сошёлся хеш,
 * вышел новый релиз) — это сотни мегабайт, которые уже никому не пригодятся. Докачивать
 * их бессмысленно (хеш всё равно не сойдётся), а место они занимают, и проверка места
 * отказывает из-за мусора, который сама же и держит. Поэтому такой остаток опознаётся
 * ([leftoverIsUsable]) и удаляется ДО проверки места, а не после.
 *
 * Отдельно про неизвестную длину: chunked-ответ `Content-Length` не несёт, и проверка
 * места по ОБЕЩАННОЙ длине на нём не работает вовсе — узел, не назвавший длину, обходил
 * её целиком. Поэтому место проверяется ещё и по ходу записи ([refuseIfSpaceRanOut]):
 * там длина не нужна, там смотрят на остаток свободного места.
 *
 * # Почему правила здесь, а не в цикле
 *
 * Цикл ввода-вывода без устройства не прогнать, а правила прогнать можно. Здесь —
 * чистая арифметика, покрытая таблицей случаев; платформенный код только исполняет
 * вердикт.
 */
object HearthDownloadLimits {

  /**
   * Потолок для APK.
   *
   * Текущие сборки — около 250 МБ, так что 512 МиБ оставляют двукратный запас на
   * рост и при этом не дают набить память телефона. Число намеренно щедрое: слишком
   * тесный потолок оставил бы семью без обновлений на ровном месте.
   */
  const val APK_LIMIT_BYTES: Long = 512L * 1024 * 1024

  /**
   * Сколько места хотим видеть сверх самого файла, чтобы телефон не встал колом.
   *
   * Шестнадцать мегабайт, а не шестьдесят четыре. Запас нужен ровно для одного: чтобы
   * ядру было куда дописать базу переписки, пока идёт загрузка. Столько оно за время
   * загрузки не пишет и близко, а разница в цене видна сразу — при сборке под 250 МБ
   * прежний запас требовал свободных ~312 МБ. На телефоне, забитом фотографиями (а в
   * семье такой каждый второй), это отказ навсегда: освободить треть гигабайта человек
   * не сможет, и обновление не поставится никогда.
   *
   * Шестнадцать против шага проверки в [SPACE_CHECK_EVERY_BYTES] (4 МБ) — четырёхкратный
   * зазор: за один шаг запас не проедается, то есть момент «места нет» мы застаём до
   * того, как оно действительно кончилось.
   */
  const val FREE_SPACE_MARGIN_BYTES: Long = 16L * 1024 * 1024

  /**
   * Узел заранее назвал длину — стоит ли вообще открывать поток.
   *
   * @param declaredBytes `Content-Length` ответа; `-1` или `0` — узел не назвал.
   * @param alreadyBytes сколько уже лежит на диске (докачка). Считается в тот же потолок.
   * @return причина отказа или `null`, если можно качать.
   */
  fun refuseIfDeclaredTooLarge(
    declaredBytes: Long,
    alreadyBytes: Long,
    limitBytes: Long = APK_LIMIT_BYTES,
  ): String? {
    if (declaredBytes <= 0L) return null
    val total = declaredBytes + alreadyBytes.coerceAtLeast(0L)
    if (total <= limitBytes) return null
    return "узел обещает файл на ${megabytes(total)} МБ — больше потолка в ${megabytes(limitBytes)} МБ"
  }

  /**
   * Длину не назвали (или соврали) — проверка по фактически записанному.
   *
   * Зовётся внутри цикла записи, поэтому считает только вычитание: всё остальное
   * здесь стоило бы процента батареи на каждые 64 КБ.
   */
  fun refuseIfWrittenTooLarge(writtenBytes: Long, limitBytes: Long = APK_LIMIT_BYTES): String? {
    if (writtenBytes <= limitBytes) return null
    return "узел отдаёт поток длиннее потолка в ${megabytes(limitBytes)} МБ"
  }

  /**
   * Хватит ли места, когда длина ИЗВЕСТНА.
   *
   * Отказать заранее лучше, чем на середине: заполненная под ноль внутренняя память
   * ломает не только обновление, но и саму переписку — ядру некуда писать базу.
   *
   * Работает только при названной длине: при `-1` судить не о чем, и здесь мы честно
   * не судим. Эту дыру закрывает не эта функция, а [refuseIfSpaceRanOut] в цикле записи.
   *
   * Текст называет ГЛАВНОЕ число — сколько не хватает. «Нужно 312, свободно 280» человек
   * вычитает в уме и ошибается; «не хватает 32 МБ» — это уже задача, которую видно, как
   * решить: одно видео из галереи.
   *
   * @param remainingBytes сколько осталось скачать; `-1` — неизвестно, тогда не судим.
   * @param usableBytes сколько места доступно приложению.
   */
  fun refuseIfNoSpace(
    remainingBytes: Long,
    usableBytes: Long,
    marginBytes: Long = FREE_SPACE_MARGIN_BYTES,
  ): String? {
    if (remainingBytes <= 0L || usableBytes <= 0L) return null
    val needed = remainingBytes + marginBytes
    if (usableBytes >= needed) return null
    return "на телефоне не хватает ${megabytesUp(needed - usableBytes)} МБ: обновление " +
      "занимает ${megabytesUp(remainingBytes)} МБ, а свободно ${megabytes(usableBytes)} МБ. " +
      "Удалите ненужные фото, видео или приложения и нажмите проверку ещё раз."
  }

  /**
   * Годится ли лежащий на диске остаток для докачки ИМЕННО этого файла.
   *
   * Рядом с остатком пишется sha256 того обновления, ради которого он качался. Без такой
   * пометки докачка вслепую продолжает ЧУЖОЙ остаток: телефон тратит трафик и место,
   * чтобы в конце не сойтись хешем и удалить всё. А до тех пор этот мусор занимает
   * место, которого на забитом телефоне и так нет.
   *
   * @param leftoverSha256 пометка рядом с остатком; `null` — пометки нет (остаток от
   *   сборок, которые её ещё не писали, или обрывок неизвестного происхождения).
   * @param wantedSha256 sha256 из манифеста.
   */
  fun leftoverIsUsable(leftoverSha256: String?, wantedSha256: String): Boolean {
    if (leftoverSha256.isNullOrBlank() || wantedSha256.isBlank()) return false
    return leftoverSha256.trim().equals(wantedSha256.trim(), ignoreCase = true)
  }

  /**
   * Как часто спрашивать файловую систему об остатке места во время записи.
   *
   * Четыре мегабайта: `usableSpace` — это системный вызов, и звать его на каждые 64 КБ
   * значило бы четыре тысячи вызовов на файл в четверть гигабайта; раз в 4 МБ — это
   * полсотни вызовов, и их не видно. Шаг уменьшен вместе с запасом
   * ([FREE_SPACE_MARGIN_BYTES], 16 МБ): за один шаг запас проедается на четверть, то
   * есть момент «места не осталось» мы по-прежнему застаём заранее.
   */
  const val SPACE_CHECK_EVERY_BYTES: Long = 4L * 1024 * 1024

  /**
   * Пора ли снова спросить про место.
   *
   * @param writtenBytes сколько записано всего.
   * @param lastCheckedAtBytes на каком объёме спрашивали в прошлый раз.
   */
  fun shouldRecheckSpace(
    writtenBytes: Long,
    lastCheckedAtBytes: Long,
    everyBytes: Long = SPACE_CHECK_EVERY_BYTES,
  ): Boolean = writtenBytes - lastCheckedAtBytes >= everyBytes

  /**
   * Место кончается ПРЯМО СЕЙЧАС — проверка по ходу записи.
   *
   * # Зачем отдельно от [refuseIfNoSpace]
   *
   * Та проверка зовётся с `Content-Length`, а при chunked-ответе его нет: `declared`
   * равен `-1`, функция выходит на первой же строке, и места не проверяется вовсе.
   * То есть узел, не назвавший длину, обходил проверку места целиком — потолок объёма
   * его ловил, а память телефона к тому времени была занята под потолок (512 МБ).
   *
   * Здесь длина не нужна: смотрим не на то, сколько осталось, а на то, сколько места
   * ещё есть. Как только свободного стало меньше запаса — останавливаемся, недокачанное
   * удаляется вызывающим, и телефон остаётся с местом для базы.
   *
   * @param usableBytes сколько места доступно приложению; `0` или меньше — прошивка не
   *   ответила, и выдумывать отказ не надо (иначе семья останется без обновлений там,
   *   где всё в порядке).
   */
  fun refuseIfSpaceRanOut(
    usableBytes: Long,
    marginBytes: Long = FREE_SPACE_MARGIN_BYTES,
  ): String? {
    if (usableBytes <= 0L) return null
    if (usableBytes >= marginBytes) return null
    return "на телефоне кончилось место: не хватает ${megabytesUp(marginBytes - usableBytes)} МБ " +
      "(свободно ${megabytes(usableBytes)} МБ). Освободите место — удалите ненужные фото, " +
      "видео или приложения — и повторите загрузку."
  }

  private fun megabytes(bytes: Long): Long = bytes / 1024 / 1024

  /**
   * Мегабайты с округлением ВВЕРХ — для чисел, которые человек читает как задачу.
   *
   * «Не хватает 0 МБ» — это не сообщение, а издевательство: не хватать может и
   * полумегабайта, и тогда честный ответ «одного мегабайта», а не «нуля».
   */
  private fun megabytesUp(bytes: Long): Long =
    if (bytes <= 0L) 0L else (bytes + 1024 * 1024 - 1) / 1024 / 1024
}
