package chat.hearth

/**
 * Что именно надо сделать с этим устройством, чтобы оно жило на своём узле.
 *
 * # Зачем правило вынесено отдельно
 *
 * Признак «телефон принадлежит контуру» жил в SharedPreferences
 * (`hearthDeviceId`), а список серверов — в базе. Это два разных носителя, и
 * восстановление архива переносит только второй. Получалось так: человек ставит
 * приложение заново, восстанавливает базу из архива — и получает базу С профилем и С
 * чужими серверами при ПУСТЫХ hearth-настройках. Экран узла при этом не показывается
 * (он привязан к «пользователя ещё нет»), `hearthEnrolled()` ложно, поэтому ни
 * отключение операторов, ни перевод релея на 443, ни чистка чужих ссылок не
 * выполняются. Устройство выглядит рабочим и не приведено ни к чему.
 *
 * Теперь решение принимается по ТРЁМ признакам сразу, и каждый из них можно
 * подставить в таблицу.
 *
 * # Почему не «просто делать всё всегда»
 *
 * Отключение операторов на ЧИСТОЙ установке оставило бы телефон вовсе без серверов:
 * своих ещё нет, чужие выключены — вместо экрана настройки человек получает ошибку.
 * Поэтому у этого шага есть своё условие: в базе уже есть хотя бы один свой сервер.
 * Ровно в этом и состояла оговорка, которая раньше была записана комментарием, а не
 * кодом, и потому применялась не туда.
 */
enum class HearthBringUpStep {
  /**
   * Показать экран узла: спросить QR или код доступа, прежде чем чат станет рабочим.
   *
   * Решение принимается здесь, а выполняется в ветке запуска (`Core.kt`), которая живёт
   * в дереве форка: там после `startChat` стоит вызов [hearthNeedsNodeOnboarding] с
   * пометкой `hearth (UPD-9)`. До него условие было только «профиля нет», и
   * восстановленная из архива база проходила мимо экрана узла — то есть оставалась
   * неучтённой на узле, а значит неотзываемой.
   *
   * Вызов там ровно один. Если ребейз его потеряет, шаг снова станет решением без
   * исполнителя — и молча.
   */
  Onboarding,

  /** Выключить операторов SimpleX, чтобы очереди не создавались на чужих релеях. */
  DisableOperators,

  /** Перевести свой релей на порт 443 (см. HearthRelayPort.kt). */
  MigrateRelayPort,

  /** Заменить адрес и приглашения, оставшиеся на чужих серверах. */
  CleanUpForeignLinks,
}

/**
 * @param enrolled заведено ли устройство на узле (есть `hearthDeviceId`).
 * @param dbHasUser есть ли в базе профиль — то есть не чистая ли это установка.
 * @param dbHasOwnServers есть ли в базе хоть один НЕ операторский SMP-сервер.
 */
fun hearthBringUpPlan(
  enrolled: Boolean,
  dbHasUser: Boolean,
  dbHasOwnServers: Boolean,
): Set<HearthBringUpStep> {
  // Чистая установка: профиля нет, трогать в базе нечего. Всё начинается с узла.
  if (!dbHasUser) return setOf(HearthBringUpStep.Onboarding)

  val steps = linkedSetOf<HearthBringUpStep>()

  // Непустая база при пустых hearth-настройках — это восстановление из архива. Честно
  // требуем QR или код: без них устройство не учтено на узле и не может быть отозвано.
  if (!enrolled) steps += HearthBringUpStep.Onboarding

  // Выключение операторов не требует ни хоста, ни токена — только чтобы телефону было
  // на чём остаться. Поэтому оно идёт и до заведения, лишь бы свои серверы в базе были.
  if (dbHasOwnServers) steps += HearthBringUpStep.DisableOperators

  // Остальное опирается на хост своего узла и на то, что устройство учтено.
  if (enrolled) {
    steps += HearthBringUpStep.MigrateRelayPort
    steps += HearthBringUpStep.CleanUpForeignLinks
  }
  return steps
}
