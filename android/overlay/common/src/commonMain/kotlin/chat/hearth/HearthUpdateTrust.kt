package chat.hearth

/**
 * Доверие к манифесту обновления.
 *
 * # Зачем
 *
 * Раньше подлинность манифеста держалась на серверном TLS — то есть на самом узле.
 * Захват узла раздачи означал власть над тем, что клиент считает свежей версией и
 * какой файл качает. Прямую подмену сборки Android отверг бы (чужая подпись не
 * установится), но заморозку — нет: узел мог просто не отдавать обновления и держать
 * людей на версии с известной дырой.
 *
 * Теперь манифест подписан ключом, которого на узле нет. Здесь — решение о доверии:
 * чистая логика, отделённая от криптографии и от сети, чтобы её можно было прогнать
 * по таблице случаев на JVM.
 *
 * # Почему отсутствие подписи — отказ
 *
 * Сборка, в которую вшит открытый ключ, обязана требовать подпись. Иначе достаточно
 * убрать `.sig` с узла, чтобы вернуться к старому — и вся защита выключается тем,
 * кого она должна останавливать.
 *
 * # Почему отсутствие КЛЮЧА — тоже отказ
 *
 * Здесь раньше стоял ранний `Allow`: нет вшитого ключа — проверять нечем, значит
 * пропускаем. Признак «эта сборка обязана проверять подпись» выводился из наличия
 * самого проверяющего материала, то есть из того, что атакующий или сбой сборки
 * может убрать. Вырезали ресурс — и манифест снова принимается от кого угодно:
 * версию, имя файла и sha256 задаёт тот, кто отвечает на `/updates/manifest.json`.
 *
 * Теперь «в сборке нет ключа» — отказ. Сборка без проверки подписи всё ещё возможна,
 * но только как ЯВНО заявленная: для неё в ресурсы кладётся отдельный флаг
 * ([HearthReleaseKey.unsignedUpdatesAllowed]), и релизный гейт `verify-apk.sh`
 * проверяет, что в релизе этого флага нет. Разница принципиальная: вырезать ресурс
 * можно молча, а дописать — значит оставить след, который гейт увидит.
 *
 * # Свежесть при недоверенных часах
 *
 * Доверенного времени на телефоне нет: часы переводит человек, и захваченный узел про
 * это знает. Поэтому свежесть проверяется тремя способами, и они независимы.
 *
 *  1. Назначенный срок: если в подписанном манифесте есть `expires`, верим ему — и
 *     больше ничему. Это решение ОПЕРАТОРА, принятое в момент подписи на рабочей
 *     станции, где лежит ключ, и подделать его нельзя: подпись накрывает весь документ.
 *     Пока срок не вышел, манифест не судят НИ правилом 2, НИ правилом 3 — оба они
 *     ЗАМЕНА решению оператора, а не добавка к нему. Раньше правило 3 срабатывало и при
 *     живом сроке, так что оператор, назначивший полгода, всё равно получал отказ у всей
 *     семьи на тридцатый день неизменного манифеста.
 *  2. Запас по возрасту — только для манифестов БЕЗ `expires`: `issued` не старше
 *     [MAX_MANIFEST_AGE_DAYS] и не из будущего дальше [FUTURE_TOLERANCE_DAYS].
 *     Правило опирается на часы устройства, поэтому его отказ прямо называет дату
 *     телефона как возможную причину.
 *  3. Прошедший локальный интервал — тоже только БЕЗ `expires`: если отметка НЕ МЕНЯЛАСЬ,
 *     а телефон прожил с ней [MAX_MANIFEST_AGE_DAYS] дней, это заморозка. Здесь нужна
 *     только разница между двумя показаниями одних и тех же часов, поэтому постоянный
 *     сдвиг правило не ломает, а перевод назад лишь откладывает отказ.
 *
 * # Почему запас по возрасту НЕ отрезает семью от обновлений
 *
 * Запас — это требование к УЗЛУ, которое узел выполнить не может: ключа подписи на нём
 * нет, переподписать манифест умеет только рабочая станция. А раздаёт узел статический
 * `manifest.json`, который переподписывают лишь при релизе. Значит, возраст манифеста
 * измеряет не здоровье узла, а частоту релизов, и любой запас, сравнимый с промежутком
 * между ними, — это не строгость, а календарь, по которому семья однажды останется без
 * обновлений просто потому, что новых версий давно не выпускали.
 *
 * Отсюда два шага и большой потолок. Старше [QUIET_NODE_AFTER_DAYS] — человеку говорят
 * «узел молчит», а обновления продолжают ставиться. Старше [MAX_MANIFEST_AGE_DAYS] —
 * отказ, и он объясняет, что делать. Ровный же путь — `expires` в подписанном манифесте:
 * тогда запас не работает вовсе, а срок назначает тот, кто знает свои обстоятельства.
 */
object HearthUpdateTrust {

  /**
   * Предельный возраст манифеста БЕЗ поля `expires`.
   *
   * Полгода. Не месяц и тем более не две недели — вот почему.
   *
   * Правило работает только на манифестах, подписанных ДО того, как появился `expires`
   * (новым `hearthctl release sign` проставляет срок всегда). Такой манифест лежит на
   * узле статическим файлом, и переподписать его может только человек у рабочей станции.
   * То есть месяц здесь означал бы «выпускайте релиз хотя бы раз в месяц, иначе семья
   * останется без канала обновлений», а спокойный месяц без релиза в семейном контуре —
   * обычное дело, и наказывать за него нечем и не за что.
   *
   * Полгода — граница, за которой «релизов давно не было» перестаёт отличаться от
   * «раздачу бросили», и при этом заведомо больше любого разумного промежутка между
   * релизами. Защита от заморозки на этом не держится: её держит то, что человек ВИДИТ
   * молчание — [QUIET_NODE_AFTER_DAYS], то есть через неделю, как требует ТЗ §1.4.
   * Отказ здесь — последняя черта, а не рабочий режим.
   *
   * # Чем платим за полгода
   *
   * Сторона против тоже настоящая: чем больше запас, тем дольше захваченный узел
   * может держать семью на замороженном манифесте старого образца. Полгода — это
   * допущенные полгода со старой версией. Счёт сходится потому, что эти полгода
   * СЛУЧАЮТСЯ только при молчании, про которое человеку говорят с седьмого дня и
   * повторяют дальше, а любой манифест, подписанный после появления `expires`, сюда не
   * попадает вовсе: у него срок стоит всегда, и стоит он по умолчанию на 30 дней. То
   * есть 180 — это потолок для УХОДЯЩЕГО образца, а не рабочий срок доверия.
   *
   * Обратный перекос дороже. Запас в 30 дней отнял бы обновления у семьи за месяц
   * без релиза — то есть в самом обычном случае из всех, и всегда одновременно у
   * всех телефонов разум. Старая версия с известной дырой хуже новой, но отсутствие
   * канала обновлений хуже обоих: через него не придёт и починка.
   *
   * # Одно число на весь проект
   *
   * Это же число стоит в `hearthd` (`model/update.rs`, `MAX_MANIFEST_AGE_DAYS`) и в
   * обоих ранбуках — `docs/runbook-release.md` и `docs/runbook-updates.md`. Расхождение
   * уже было: в runbook-release значилось 30, и оператор, читая документацию, ждал отказа
   * там, где его не было, и не ждал там, где он есть. Правка числа здесь обязана
   * идти вместе с правкой в тех трёх местах; сторож на само число — в
   * HearthUpdateTrustTest.
   */
  const val MAX_MANIFEST_AGE_DAYS: Long = 180

  /**
   * Через сколько дней возраст манифеста становится ВИДЕН человеку.
   *
   * Семь — горизонт ТЗ §1.4. До этой границы молчание узла — обычное дело: новых версий
   * может просто не быть. После — это уже новость, и человек должен её получить. Но
   * новость, а не отказ: отказ на седьмой день оставил бы без обновлений ровно ту
   * семью, которой они нужнее всего.
   */
  const val QUIET_NODE_AFTER_DAYS: Long = 7

  /**
   * Насколько отметка может опережать часы телефона.
   *
   * Сутки: часовые пояса, неточные часы и момент выпуска релиза в другом полушарии
   * дают законный разбег в несколько часов. Без этого допуска узел мог бы ставить
   * дату вперёд и обходить правило возраста, а с ним — нет: он выигрывает сутки, а не
   * бесконечность.
   */
  const val FUTURE_TOLERANCE_DAYS: Long = 1

  /**
   * Через сколько дней молчание узла показывается человеку.
   *
   * Было 30 и не вызывалось нигде, потом 14. Теперь семь — тот же горизонт, что у
   * [QUIET_NODE_AFTER_DAYS], и та же мысль: «узел неделю не отвечал на проверку» и
   * «узел неделю не публиковал нового» человек слышит одинаково рано и одинаково
   * необидно. Это счётчик молчания, а не отказ, так что ранняя граница тут дёшева.
   */
  const val STALE_AFTER_DAYS: Long = 7

  /**
   * Сколько РАЗНЫХ дней подряд надо безуспешно стучаться, чтобы сказать «узел молчит».
   *
   * Считаются попытки, а не календарь. Телефон, который сам неделю не выходил в сеть
   * (уехали, выключили, кончился интернет), к узлу не обращался ни разу — обвинять узел
   * в этом нельзя: человек пойдёт к владельцу узла зря, а тот ничего не найдёт.
   *
   * Три ДНЯ, а не три попытки: приложение выходит на передний план много раз за день, и
   * три неудачи подряд случаются за двадцать минут из-за одного перезагружающегося
   * роутера. Три разных дня без единого ответа — это уже не совпадение.
   */
  const val MIN_SILENT_ATTEMPT_DAYS: Long = 3

  /**
   * За сколько дней до конца назначенного срока предупредить человека.
   *
   * Те же семь дней, что у [QUIET_NODE_AFTER_DAYS], и по той же причине: узел сам
   * переподписать манифест не может, значит единственный способ избежать отказа — успеть
   * сказать человеку РАНЬШЕ, чем срок выйдет. Это предупреждение, а не отказ.
   */
  const val EXPIRY_WARNING_DAYS: Long = 7

  sealed interface Verdict {
    /**
     * Манифесту верим.
     *
     * @param notice что при этом надо сказать человеку; `null` — говорить не о чем.
     *   Непустым он бывает, когда узел давно не публиковал нового: раньше этот случай
     *   был отказом, и «узел молчит» звучало как «обновлений вам больше не будет».
     */
    data class Allow(val notice: String? = null) : Verdict
    data class Refuse(val reason: String) : Verdict
  }

  /**
   * @param hasPinnedKey вшит ли в сборку открытый ключ.
   * @param signaturePresent лежит ли рядом с манифестом `.sig`.
   * @param signatureValid сошлась ли подпись (проверяется платформой).
   * @param issued отметка времени в манифесте, RFC 3339.
   * @param expires назначенный оператором срок годности манифеста, RFC 3339; `null` —
   *   поля нет (манифест прежних версий), тогда работает запас по возрасту. Поле лежит
   *   ВНУТРИ подписанного документа, поэтому узел его не подделает: подпись накрывает
   *   весь манифест целиком.
   * @param lastSeenIssued самая свежая отметка, которую этот телефон уже видел.
   * @param nowEpochDays сегодняшний день по часам телефона.
   * @param firstSeenEpochDays день, когда телефон впервые увидел [lastSeenIssued];
   *   `null` — такой отметки ещё не было.
   * @param unsignedUpdatesAllowed объявлено ли ресурсом, что эта сборка сознательно
   *   собрана без ключа. Без такого объявления отсутствие ключа — отказ.
   */
  fun decide(
    hasPinnedKey: Boolean,
    signaturePresent: Boolean,
    signatureValid: Boolean,
    issued: String?,
    lastSeenIssued: String?,
    nowEpochDays: Long,
    firstSeenEpochDays: Long? = null,
    unsignedUpdatesAllowed: Boolean = false,
    maxAgeDays: Long = MAX_MANIFEST_AGE_DAYS,
    expires: String? = null,
    quietAfterDays: Long = QUIET_NODE_AFTER_DAYS,
  ): Verdict {
    if (!hasPinnedKey) {
      if (!unsignedUpdatesAllowed) {
        // Проверять нечем — значит и разрешать нечем. Раньше здесь стоял Allow.
        //
        // Текст называет действие целиком, потому что дальше человеку его никто не
        // подскажет: этот отказ не проходит сам ни через день, ни через месяц, и «нет
        // ключа» без продолжения звучит как поломка, к которой непонятно как подступиться.
        return Verdict.Refuse(
          "в этой сборке нет ключа проверки обновлений — проверить, что обновление " +
            "пришло от вашего узла, нечем. Переустановите приложение сборкой с узла: " +
            "попросите у владельца узла ссылку или QR и поставьте её поверх этой. " +
            "Переписка и звонки продолжают работать."
        )
      }
      // Сборка заявлена как неподписанная. Подпись не проверяем, но свежесть — да:
      // она от ключа не зависит, а заморозка одинаково опасна в любой сборке.
    } else {
      if (!signaturePresent) {
        return Verdict.Refuse("манифест обновления не подписан")
      }
      if (!signatureValid) {
        return Verdict.Refuse("подпись манифеста не сошлась")
      }
    }

    if (issued.isNullOrBlank()) {
      return Verdict.Refuse("в манифесте нет отметки времени")
    }
    // Неразобранная отметка — это отсутствие проверки свежести. Раньше сравнение шло
    // по строкам, и такой манифест молча проходил.
    val issuedDay = hearthEpochDaysOf(issued)
      ?: return Verdict.Refuse("отметка времени манифеста не разобрана: $issued")

    // Откат метаданных: узел показывает манифест старее уже виденного. Так выглядит
    // попытка удержать телефон на прежней версии. Сравниваем эпохи, а не строки:
    // 2026-09-12T11:00:00+03:00 лексикографически меньше, чем 2026-09-12T08:00:00Z.
    val lastSeenDay = hearthEpochDaysOf(lastSeenIssued)
    if (lastSeenDay != null && issuedDay < lastSeenDay) {
      return Verdict.Refuse("манифест старее уже полученного")
    }

    if (issuedDay - nowEpochDays > FUTURE_TOLERANCE_DAYS) {
      return Verdict.Refuse(
        "манифест датирован будущим ($issued) — проверьте дату на телефоне"
      )
    }

    // Свежесть: сначала назначенный срок, и только если его нет — запас по возрасту.
    var notice: String? = null
    // Срок назначен и ещё не вышел. Тогда отключаются ОБА запасных правила — и возраст,
    // и заморозка (ниже): шапка файла обещает именно это, а код до сих пор обещание
    // нарушал — неизменный манифест с честным сроком до декабря отказывал у всей семьи
    // задолго до декабря, по правилу заморозки.
    var withinDeclaredExpiry = false
    if (!expires.isNullOrBlank()) {
      // Поле есть, но не разобралось — отказ. Это не «поля нет», а «поле есть, и оно не
      // то»: молча считать такой манифест бессрочным значит выключить проверку тем же
      // способом, каким её выключали бы нарочно.
      val expiresDay = hearthEpochDaysOf(expires)
        ?: return Verdict.Refuse("срок годности манифеста не разобран: $expires")
      if (nowEpochDays > expiresDay) {
        return Verdict.Refuse(
          "срок годности манифеста обновления истёк ($expires). Узел больше не публикует " +
            "обновления — свяжитесь с владельцем узла и попросите переподписать манифест. " +
            "Если на телефоне сбита дата, поправьте сначала её. Переписка и звонки " +
            "продолжают работать."
        )
      }
      // Возрастом такой манифест не судим: срок назначил оператор на своей станции, где
      // лежит ключ, а мы здесь не умнее его. Запас по возрасту — замена этому решению,
      // а не добавка к нему.
      withinDeclaredExpiry = true
      // Но о приближении конца срока говорим заранее: переподписать манифест может
      // только человек у станции, и узнать о сроке в день его истечения — значит узнать
      // поздно. Это предупреждение, обновления продолжают ставиться.
      val leftDays = expiresDay - nowEpochDays
      if (leftDays == 0L) {
        notice = "Сегодня последний день срока манифеста обновлений ($expires). Обновления " +
          "пока ставятся, но завтра телефон перестанет их принимать. Попросите владельца " +
          "узла переподписать манифест сегодня."
      } else if (leftDays <= EXPIRY_WARNING_DAYS) {
        notice = "Обновлениям с узла осталось верить $leftDays дн.: срок манифеста " +
          "кончается $expires. Обновления пока ставятся. Попросите владельца узла " +
          "переподписать манифест до этого дня."
      }
    } else {
      val ageDays = nowEpochDays - issuedDay
      if (ageDays > maxAgeDays) {
        return Verdict.Refuse(
          "манифест старше $maxAgeDays дней ($issued): узел давно не переподписывал его — " +
            "или на телефоне сбита дата. Проверьте дату на телефоне, а если она верна — " +
            "попросите владельца узла обновить манифест. Переписка и звонки продолжают " +
            "работать."
        )
      }
      if (ageDays > quietAfterDays) {
        // Не отказ. Узел мог просто не выпускать новых версий, и отрезать семью от
        // обновлений на этом основании нельзя. Но и молчать об этом нельзя тоже.
        notice = "Узел молчит: свежее обновление не публиковали $ageDays дней ($issued). " +
          "Обновления пока ставятся. Если так и останется — спросите владельца узла."
      }
    }

    // Заморозка при переведённых часах: отметка та же, что и в прошлый раз, но телефон
    // прожил с ней целое окно. Здесь считается только разница локальных показаний,
    // поэтому сдвиг часов правило не обходит, а лишь откладывает.
    //
    // При ЖИВОМ назначенном сроке правило пропускается. Оно — замена решению оператора
    // на случай, когда решения нет; когда оно есть, «манифест не менялся полгода» и есть
    // то, о чём оператор договорился, подписав срок на полгода. Иначе неизменный
    // манифест с честным сроком до декабря отказывал бы у всей семьи в ноябре.
    if (!withinDeclaredExpiry && firstSeenEpochDays != null && issued == lastSeenIssued &&
      nowEpochDays - firstSeenEpochDays >= maxAgeDays
    ) {
      return Verdict.Refuse(
        "узел $maxAgeDays дней отдаёт один и тот же манифест — обновления остановились. " +
          "Свяжитесь с владельцем узла. Переписка и звонки продолжают работать."
      )
    }

    return Verdict.Allow(notice)
  }

  /**
   * Давно ли приходили обновления — и ПЫТАЛИСЬ ли мы вообще их получить.
   *
   * Захваченный узел не может подсунуть своё, но может молчать. Молчание — тоже
   * событие, и человек должен о нём узнать, а не считать, что новостей нет.
   *
   * # Почему одного календаря мало
   *
   * Раньше здесь была только разница дней, и телефон, который сам неделю не выходил в
   * сеть (уехали без интернета, выключили, кончились деньги на связи), обвинял узел:
   * человека посылали к владельцу узла, а узел был жив и здоров. «Мы не пытались» и
   * «пытались и не ответили» — разные вещи, и различать их обязано именно это правило.
   *
   * Поэтому нужны ОБА признака: прошло не меньше [STALE_AFTER_DAYS] с последнего ответа
   * И было не меньше [MIN_SILENT_ATTEMPT_DAYS] разных дней, когда мы стучались и не
   * получили ничего. Календарь один молчанием узла больше не считается.
   *
   * `lastSuccessEpochDays == null` — проверки не было ни разу. Это не «всё хорошо»:
   * так выглядит свежеустановленное приложение, и тревожить человека на первом
   * запуске незачем. Отметку ставит первая же удавшаяся проверка.
   *
   * @param failedAttemptDays сколько РАЗНЫХ дней после последнего ответа телефон
   *   пытался связаться с узлом и не получил ответа.
   */
  fun isStale(
    lastSuccessEpochDays: Long?,
    todayEpochDays: Long,
    failedAttemptDays: Long = 0,
    limitDays: Long = STALE_AFTER_DAYS,
    minAttemptDays: Long = MIN_SILENT_ATTEMPT_DAYS,
  ): Boolean {
    if (lastSuccessEpochDays == null) return false
    // Ни одной попытки — узел ни в чём не виноват, молчали мы сами.
    if (failedAttemptDays < minAttemptDays) return false
    return todayEpochDays - lastSuccessEpochDays >= limitDays
  }
}
