package chat.hearth

import chat.simplex.common.platform.Log

/**
 * Приведение приложения к своему узлу — после того, как чат стал рабочим.
 *
 * # Зачем отдельный файл
 *
 * Раньше эти шаги стояли подряд в одной ветке запуска (`Core.kt`), ничем не
 * защищённые. Любая осечка на первом из них обрывала **все** остальные: не
 * применялись настройки узла, не выключались операторы SimpleX, не заменялись
 * адреса. Приложение оставалось на публичных серверах и спокойно создавало
 * приглашение вида `smp11.simplex.im` — молча, без следа в интерфейсе.
 *
 * Ровно это и случилось: чат был остановлен, первый же вызов ответил
 * `chatNotStarted`, исключение улетело наружу, и защита не сработала целиком.
 *
 * # Что изменилось
 *
 * Каждый шаг защищён сам по себе: падение одного не отменяет соседей. И вызывается
 * всё это не из одной ветки запуска, а из той точки, где чат ДЕЙСТВИТЕЛЬНО стал
 * рабочим, — значит срабатывает и при обычном старте приложения, и при ручном
 * включении чата из настроек базы данных, откуда раньше не срабатывало вовсе.
 *
 * # Почему «идёт» и «получилось» — разные признаки
 *
 * Было одно поле `done`, и оно совмещало два смысла: «защита от повторного входа при
 * конкурентных `startChat`» и «приведение отработало». Ставилось оно ПЕРВОЙ строкой,
 * до единого шага, а читалось как второе. Значит любая осечка (ядро отказало, сеть
 * моргнула, профиль не готов) записывалась в журнал — и повтора не было до конца
 * жизни процесса. Операторы SimpleX могли остаться включёнными: тот самый сценарий,
 * ради которого файл и написан.
 *
 * Теперь признака два. [inProgress] ставится перед шагами и снимается в `finally` —
 * он и только он защищает от второго захода. [done] ставится, лишь когда ВСЕ шаги
 * ответили [HearthStepOutcome.Done].
 *
 * # Почему повтор ограничен
 *
 * Незаконченная цепочка повторяется — иначе телефон, у которого шаг не прошёл (ядро
 * было не готово, сети не было), остался бы неприведённым до перезапуска приложения.
 * Но точка повтора — выход приложения на передний план, а он случается десятки раз в
 * день. Пока цепочка не прошла целиком (а на незаведённом устройстве она не пройдёт
 * никогда), шаги выполнялись бы при каждом таком выходе — включая перевод релея на
 * порт 443, который ХОДИТ В СЕТЬ. На плохой связи это повторяющееся ожидание ровно на
 * том пути, где человек ждёт список чатов.
 *
 * Поэтому повтор ограничен вдвойне: не чаще [MIN_GAP_MS] и не больше [MAX_ATTEMPTS]
 * раз за жизнь процесса. Оба ограничения снимает [reset] — его зовут, когда появилась
 * новая причина пробовать: чат перезапустили или человек только что применил bundle.
 */
object HearthStartup {

  /**
   * Не чаще, чем раз в четверть часа.
   *
   * Минуты `HearthResume` здесь мало: там дешёвое переподключение к релеям, здесь —
   * несколько запросов к ядру и один поход в сеть. Четверть часа — достаточно редко,
   * чтобы не мешать, и достаточно часто, чтобы починившееся за обед устройство
   * привелось само, без перезапуска приложения.
   */
  const val MIN_GAP_MS: Long = 15 * 60_000

  /**
   * Сколько раз пробовать за жизнь процесса.
   *
   * Шесть попыток — это полтора часа с [MIN_GAP_MS]. Если за полтора часа не вышло,
   * дело не в моргнувшей сети, и дёргать ядро и узел дальше незачем: следующий запуск
   * приложения начнёт счёт заново.
   */
  const val MAX_ATTEMPTS: Int = 6

  @Volatile
  private var attempts: Int = 0

  @Volatile
  private var lastRunMs: Long = 0

  /**
   * Цепочка сейчас выполняется.
   *
   * Защита от повторного входа: чат может запускаться несколько раз за жизнь процесса,
   * и две параллельные цепочки дёргали бы ядро вдвое на пути, где человек ждёт списка
   * чатов.
   */
  @Volatile
  private var inProgress = false

  /**
   * Цепочка отработала ПОЛНОСТЬЮ.
   *
   * Только это состояние отменяет повтор. Незаконченная цепочка повторится при
   * следующем запуске чата.
   */
  @Volatile
  private var done = false

  /**
   * Сбрасывается, когда чат остановлен: следующий запуск снова всё проверит.
   *
   * Счётчик попыток и отметка времени сбрасываются вместе с признаками. Иначе
   * человек, применивший bundle после исчерпания попыток, не получил бы приведения
   * вовсе — а именно в этот момент оно и стало возможным.
   */
  fun reset() {
    done = false
    inProgress = false
    attempts = 0
    lastRunMs = 0
  }

  /**
   * Свободна ли цепочка: не идёт сейчас и не отработала целиком.
   *
   * `internal`, а не публичная: из продуктового кода её зовёт одна [begin] — снаружи
   * пакета `chat.hearth` решение «пора ли» принимать нельзя, иначе ограничение
   * повторов обойдут, не заметив. Видимой она остаётся для commonTest (тестовая
   * компиляция дружественна главной): [done] и [inProgress] приватны, и другого
   * способа увидеть, что незаконченная цепочка осталась незаконченной, у теста нет —
   * см. HearthStartupTest, «неудача помечена как выполненное приведение».
   */
  internal fun shouldRun(): Boolean = !done && !inProgress

  /**
   * Занять цепочку. `false` — повторять незачем или ещё рано.
   *
   * @param nowMs текущий момент; параметром, чтобы правило повтора проверялось тестом.
   */
  fun begin(nowMs: Long = hearthNowEpochMillis()): Boolean {
    if (!shouldRun()) return false
    if (!hearthStartupDue(attempts, lastRunMs, nowMs)) return false
    attempts += 1
    lastRunMs = nowMs
    inProgress = true
    return true
  }

  /** Освободить цепочку. [allDone] — все ли шаги действительно выполнены. */
  fun finish(allDone: Boolean) {
    if (allDone) done = true
    inProgress = false
  }
}

/**
 * Пора ли повторять цепочку приведения. Чистое правило — чтобы его можно было
 * прогнать на JVM, а не проверять секундомером на телефоне.
 *
 * @param attempts сколько раз цепочка уже запускалась за жизнь процесса.
 * @param lastRunMs когда запускалась в последний раз.
 * @param nowMs текущий момент.
 *
 * Первый заход не ограничен ничем: на пути обычного запуска приложения задержки быть
 * не должно. Часы, переведённые НАЗАД, тоже разрешают заход — иначе одно неверное
 * значение времени заперло бы приведение до перезапуска приложения.
 */
fun hearthStartupDue(
  attempts: Int,
  lastRunMs: Long,
  nowMs: Long,
  minGapMs: Long = HearthStartup.MIN_GAP_MS,
  maxAttempts: Int = HearthStartup.MAX_ATTEMPTS,
): Boolean {
  if (attempts <= 0) return true
  if (attempts >= maxAttempts) return false
  if (nowMs < lastRunMs) return true
  return nowMs - lastRunMs >= minGapMs
}

/**
 * Чем кончился шаг приведения.
 *
 * Три исхода, а не два, и это принципиально. Раньше шаги отвечали `Boolean`, и `false`
 * означало одновременно «ядро отказало» и «этому устройству шаг не нужен» — например,
 * когда bundle ещё не применён. Считать второе успехом значило бы навсегда оставить
 * без приведения телефон, который заведут через час.
 */
enum class HearthStepOutcome {
  /** Сделано или делать было нечего. */
  Done,

  /** Шагу не за что взяться: устройство ещё не заведено, хоста узла нет. Повторить позже. */
  NotApplicable,

  /** Не получилось. Повторить позже. */
  Failed,
}

/** Один шаг приведения: имя для журнала и что сделать. */
class HearthStartupStep(val name: String, val run: suspend () -> HearthStepOutcome)

/**
 * Привести приложение к своему узлу. Вызывается из `startChat`.
 *
 * Сетевых вызовов здесь нет намеренно: обновление TURN-кредов и удаление чужих
 * ссылок ходят в сеть, а на пути запуска это означает ожидание до сорока пяти секунд
 * при нестабильном соединении — с вечным «загрузка чатов» на экране. Они запускаются
 * отдельно, в фоне.
 *
 * @param steps шаги параметром, чтобы цепочку можно было прогнать на JVM: настоящие
 *   шаги тянут `ChatController`, которого в тесте нет.
 * @param nowMs текущий момент — для правила повтора ([hearthStartupDue]).
 */
suspend fun hearthAfterChatStarted(
  steps: List<HearthStartupStep> = hearthDefaultStartupSteps(),
  nowMs: Long = hearthNowEpochMillis(),
) {
  if (!HearthStartup.begin(nowMs)) return
  var allDone = true
  try {
    for (step in steps) {
      if (hearthStep(step) != HearthStepOutcome.Done) allDone = false
    }
  } finally {
    // finally, а не последняя строка: бросок из шага не должен оставить цепочку
    // навсегда «занятой» — тогда её не повторит никто.
    HearthStartup.finish(allDone)
  }
}

/** Настоящие шаги. Вынесены из [hearthAfterChatStarted], чтобы её можно было тестировать. */
fun hearthDefaultStartupSteps(): List<HearthStartupStep> = listOf(
  HearthStartupStep("настройки узла") {
    // true здесь значит «применять было нечего или применилось»; false — bundle лежит
    // и не лёг, и человека вернут на экран узла.
    if (hearthApplyPendingBundle()) HearthStepOutcome.Done else HearthStepOutcome.Failed
  },
  HearthStartupStep("свои серверы") { hearthEnforceOwnServers() },
  HearthStartupStep("порт релея") { hearthMigrateRelayToWebPort() },
  HearthStartupStep("карточки-пресеты") {
    hearthRemovePresetContactCards()
    HearthStepOutcome.Done
  },
)

/**
 * Обновить состояние «устройство не заведено на узле» — без единого сетевого вызова.
 *
 * Стоит отдельно от [hearthDefaultStartupSteps] намеренно: это не шаг приведения, а
 * наблюдение за ним. Если бы оно было шагом, незаведённое устройство навсегда держало
 * бы цепочку незаконченной и тем самым продлевало повторы, ради ограничения которых
 * всё это и написано.
 */
suspend fun hearthNoteNodeSetup() {
  HearthNodeSetup.notOnNode.value = runCatching { hearthNeedsNodeOnboarding() }.getOrDefault(false)
}

/**
 * Один шаг приведения.
 *
 * Неудача пишется в журнал и НЕ прерывает остальные: защита, которая выключается
 * целиком от одной осечки, хуже, чем её отсутствие, — потому что человек уверен, что
 * она работает. Но теперь неудача ещё и ВОЗВРАЩАЕТСЯ: без этого даже готовая повторная
 * попытка не знала бы, что повторять.
 */
private suspend fun hearthStep(step: HearthStartupStep): HearthStepOutcome {
  val outcome = runCatching { step.run() }.getOrElse { e ->
    Log.e("hearth", "шаг «${step.name}» не выполнен: ${e.message}")
    HearthStepOutcome.Failed
  }
  if (outcome == HearthStepOutcome.NotApplicable) {
    Log.w("hearth", "шаг «${step.name}» пока не применим — повторим при следующем запуске")
  }
  return outcome
}
